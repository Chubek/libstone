def opc(source, name, mnemonic=0, **kwargs):
    return Table('opcodes/' + source, name, mnemonic, **kwargs)


def hdr(source, name, mnemonic=0, **kwargs):
    return Table('include/opcode/' + source, name, mnemonic, **kwargs)


