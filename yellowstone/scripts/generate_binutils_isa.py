def uncomment(text):
    return COMMENTS.sub(lambda m: m[0] if m[0][0] in '\"\'' else
                        re.sub(r'[^\n]', ' ', m[0]), text)


def punctuation(text):
    for match in TOKENS.finditer(text):
        if match[0][0] not in '\"\'':
            yield match.start(), match[0]


def closing(text, start):
    depth = 0
    for offset, token in punctuation(text[start:]):
        if token == '{':
            depth += 1
        elif token == '}':
            depth -= 1
            if depth == 0:
                return start + offset
    raise ValueError('Unclosed C initializer')


def fields(text):
    result, depth, start = [], 0, 0
    for offset, token in punctuation(text):
        if token in '({[':
            depth += 1
        elif token in ')}]':
            depth -= 1
        elif token == ',' and depth == 0:
            result.append(text[start:offset].strip())
            start = offset + 1
    if depth:
        raise ValueError('Unbalanced C initializer')
    if text[start:].strip():
        result.append(text[start:].strip())
    return result


def table_span(text, name):
    found = re.search(r'\b' + re.escape(name) + r'\s*(?:\[[^\]]*\])+\s*=\s*\{', text)
    if not found:
        raise ValueError(f'Missing table: {name}')
    start = found.end() - 1
    return start, closing(text, start)


def rows(text, name):
    start, end = table_span(text, name)
    depth = 0
    for pos, token in punctuation(text[start + 1:end]):
        if token == '{':
            if depth == 0:
                row_start = pos
            depth += 1
        elif token == '}':
            depth -= 1
            if depth == 0:
                offset = start + 1 + row_start
                yield text.count('\n', 0, offset), fields(text[offset + 1:start + 1 + pos])


def compact(text):
    # Normalize whitespace outside C literals, retaining escapes and operands.
    return re.sub(rf'{common.STRING}|{CHAR}|\s+',
                  lambda m: m[0] if m[0][0] in '\"\'' else ' ', text).strip()


def string_field(text):
    return common.quoted(text.strip().strip('{}').strip())


def mnemonic(template):
    match = re.match(r'[A-Za-z_][A-Za-z0-9_.:/+!\-]*', template.strip())
    return match[0] if match else ''


class Inventory:
    def __init__(self, root, command='cc'):
        self.root = Path(root)
        self.command = command

    @lru_cache(maxsize=None)
    def read(self, source):
        return (self.root / source).read_text()

    @lru_cache(maxsize=None)
    def preprocess(self, source, prefix='', includes=()):
        def expand(path):
            text = uncomment(self.read(path))
            def include(match):
                local = 'include/' + match[1]
                if local not in includes:
                    return ' ' * len(match[0])
                line = text.count('\n', 0, match.end()) + 2
                return f'#line 1 "{local}"\n{expand(local)}\n#line {line} "{path}"'
            return re.sub(r'^[ \t]*#include\s+[<"]([^>"\n]+)[>"][^\n]*', include, text, flags=re.M)
        output = common.cpp(prefix + f'\n#line 1 "{source}"\n' + expand(source), self.command, True)
        text, origins, path, line = [], [], source, 1
        for item in output.split('\n'):
            mark = re.match(r'#\s+(\d+)\s+"([^"]+)"', item)
            if mark:
                line, path = int(mark[1]), mark[2]
            else:
                text.append(item)
                origins.append((path, line))
                line += 1
        return '\n'.join(text), origins

    def reference(self, origin, table, **data):
        source, line = origin
        if not (self.root / source).is_file():
            raise ValueError(f'Untraceable preprocessor origin: {origin}')
        return dict(source='binutils/' + source, line=line, table=table, **data)

    def generic(self, arch):
        result = []
        for spec in TABLES[arch]:
            text, origins = self.preprocess(spec.source, spec.prefix, spec.includes)
            accepted = 0
            for line, values in rows(text, spec.name):
                if len(values) <= spec.mnemonic:
                    continue  # Null sentinel.
                try:
                    name = string_field(values[spec.mnemonic])
                except ValueError:
                    if values[spec.mnemonic] in ('0', '(0)', 'NULL', '(void *)0'):
                        continue
                    raise ValueError(f'{spec.source}:{origins[line]}: nonliteral mnemonic {values}')
                if not name.strip() or name.strip().lower() in ('bad', 'invalid', 'undefined', '???'):
                    continue
                key = mnemonic(name) if spec.template else name.strip()
                if not key:
                    continue
                if arch in ('m68hc11', 'm68hc12') and spec.name == 'm68hc11_opcodes':
                    cpu = 'cpu6811' if arch == 'm68hc11' else 'cpu6812'
                    if cpu not in values[-1]:
                        continue
                names = spec.columns.split()
                if names and len(names) != len(values):
                    raise ValueError(f'{spec.name}: {len(names)} columns, {len(values)} values: {values}')
                data = dict(mnemonic=key, source_fields=[compact(v) for v in values])
                if names:
                    data['field_names'] = names
                if spec.template:
                    data['assembler_template'] = name
                result.append(self.reference(origins[line], spec.name, **data))
                accepted += 1
            if not accepted:
                raise ValueError(f'Empty instruction inventory for {arch}: {spec.name}')
        return result

    def cgen(self, arch):
        source, op_source = f'opcodes/{arch}-desc.c', f'opcodes/{arch}-opc.c'
        text, op_text = uncomment(self.read(source)), uncomment(self.read(op_source))
        base_table, opcode_table = f'{arch}_cgen_insn_table', f'{arch}_cgen_insn_opcode_table'
        bases, opcodes = list(rows(text, base_table)), list(rows(op_text, opcode_table))
        if len(bases) != len(opcodes):
            raise ValueError(f'{arch}: CGEN base/opcode table lengths differ')
        formats = {}
        for match in re.finditer(r'\b(ifmt_\w+)\s+ATTRIBUTE_UNUSED\s*=\s*\{', op_text):
            end = closing(op_text, match.end() - 1)
            formats[match[1]] = fields(op_text[match.end():end])
        result = []
        for (line, base), (op_line, opcode) in zip(bases, opcodes):
            if base[0] == '0':
                continue
            name, asm_name = string_field(base[1]), string_field(base[2])
            data = dict(mnemonic=asm_name, instruction_id=name, encoding_bits=int(base[3]),
                        attributes=compact(base[4]), opcode_source='binutils/' + op_source,
                        opcode_line=op_line + 1, opcode_fields=[compact(v) for v in opcode])
            fmt = re.search(r'ifmt_\w+', opcode[2])
            if fmt and fmt[0] in formats:
                f = formats[fmt[0]]
                data['format'] = fmt[0]
                data['format_fields'] = [compact(v) for v in f]
                data['match_bits'] = int(f[0])
                data['mask'] = common.Hex(int(f[2], 0))
                data['match'] = common.Hex(int(opcode[3].strip('{} '), 0))
            result.append(self.reference((source, line + 1), base_table, **data))
        return result

    def bfin(self):
        source = 'opcodes/bfin-dis.c'
        text = uncomment(self.read(source))
        result = []
        pattern = r'else if \(([^\n]+)\)\s*rv = (decode_\w+) \(([^;]+)\);'
        for match in re.finditer(pattern, text):
            function = match[2]
            definition = re.search(r'\n' + function + r'\s*\([^;]+?\)\s*\{', text)
            if not definition:
                raise ValueError(f'No decoder definition: {function}')
            end = closing(text, definition.end() - 1)
            fragments = re.findall(r'OUTS\s*\(outf,\s*(' + common.STRING + r')\)',
                                   text[definition.end():end])
            result.append(self.reference((source, text.count('\n', 0, match.start()) + 1),
                '_print_insn_bfin', mnemonic=function.removeprefix('decode_'),
                kind='decoder_family', decoder=function, predicate=compact(match[1]),
                encoding_bits=32 if 'iw1' in match[3] else 16,
                display_fragments=list(dict.fromkeys(common.quoted(v) for v in fragments))))
        # The multi-issue NOP has a direct dispatch branch, not a decode_* call.
        match = re.search(r'if \((\(iw0 & 0xf7ff\)[^\n]+)\)', text)
        result.append(self.reference((source, text.count('\n', 0, match.start()) + 1),
            '_print_insn_bfin', mnemonic='MNOP', encoding_bits=32, predicate=match[1]))
        return result

    def rx(self):
        source = 'opcodes/rx-decode.opc'
        text = self.read(source)
        result = []
        for match in re.finditer(r'/\*\*\s*([01][^\n]*?)\t+([^\n]*?)\s*\*/', text):
            pattern, template = match[1].strip(), match[2].strip()
            result.append(self.reference((source, text.count('\n', 0, match.start()) + 1),
                'rx_decode_opcode', mnemonic=mnemonic(template), bit_pattern=pattern,
                assembler_template=template, kind='decoder_pattern'))
        return result

    def z80(self):
        source = 'opcodes/z80-dis.c'
        text = uncomment(self.read(source))
        result = []
        for table in re.findall(r'struct tab_elt\s+(\w+)\[\]\s*=', text):
            for line, values in rows(text, table):
                template = string_field(values[3])
                name = mnemonic(template)
                if not name or name in ('xx', 'ix', 'iy') or values[2] == 'dump':
                    continue
                result.append(self.reference((source, line + 1), table, mnemonic=name,
                    assembler_template=template, decoder=values[2],
                    opcode_byte=common.Hex(int(values[0], 0)), mask_byte=common.Hex(int(values[1], 0))))
        # These small mnemonic tables are expanded by callbacks, not opc_main.
        for table in ('arit_str', 'cb1_str', 'cb2_str'):
            start, end = table_span(text, table)
            for index, value in enumerate(fields(text[start + 1:end])):
                template = string_field(value)
                if template:
                    result.append(self.reference((source, text.count('\n', 0, start) + 1), table,
                        mnemonic=mnemonic(template), selector=index, assembler_template=template))
        # Block transfer/compare/input/output names are synthesized by cis().
        found = re.search(r'\ncis\s*\([^;]+?\)\s*\{', text)
        if found:
            start, end = table_span(text[found.end():], 'opar')
            names = [string_field(v) for v in fields(text[found.end() + start + 1:found.end() + end])]
            for code in range(256):
                if code & 0xe4 != 0xa0:
                    continue
                base = 'ot' if code & 0x13 == 0x13 else names[code & 3]
                name = base + ('d' if code & 8 else 'i') + ('r' if code & 0x10 else '')
                result.append(self.reference((source, text.count('\n', 0, found.end()) + 1),
                    'cis', mnemonic=name, prefix_byte=common.Hex(0xed),
                    opcode_byte=common.Hex(code), mask_byte=common.Hex(0xff)))
        return result

    @lru_cache(maxsize=1)
    def old_tables(self):
        return common.load_tables(self.root, self.command)

    def instructions(self, arch):
        if arch in CGEN:
            return self.cgen(arch)
        if arch in TABLES:
            return self.generic(arch)
        if arch in ('bfin', 'rx', 'z80'):
            return getattr(self, arch)()
        if arch in ('i386', 'l1om', 'k1om'):
            excluded = 'Cpu64' if arch == 'i386' else 'CpuNo64'
            return [row for row in self.old_tables()['x86'] if excluded not in row['cpu_flags'].split('|')]
        if arch == 'rs6000':
            # print_insn_rs6000 selects exactly PPC_OPCODE_POWER (ppc-dis.c).
            records = self.old_tables()['ppc']
            source = self.read('opcodes/ppc-opc.c').split('powerpc_opcodes[]', 1)[0]
            definitions = common.defines(self.read('include/opcode/ppc.h')) + '\n' + common.defines(source)
            expressions = ['PPC_OPCODE_POWER'] + [value for row in records
                                                   for value in (row['flags'], row['deprecated'])]
            output = common.cpp(definitions + '\n' + '\n'.join('ISA_FLAG ' + x for x in expressions),
                                self.command)
            numbers = [common.integer(value.replace('(ppc_cpu_t)', ''))
                       for value in re.findall(r'^ISA_FLAG (.+)$', output, re.M)]
            if len(numbers) != len(expressions):
                raise ValueError('Missing PowerPC dialect expressions')
            dialect = numbers[0]
            return [row for i, row in enumerate(records)
                    if numbers[1 + 2*i] & dialect and not numbers[2 + 2*i] & dialect]
        raise ValueError(f'Unmapped dispatcher architecture: {arch}')

    def dimensions(self, arch):
        cpu = {'mn10200': 'm10200', 'mn10300': 'm10300'}.get(arch, arch)
        source = f'bfd/cpu-{cpu}.c'
        text, origins = self.preprocess(source, '#define BFD64 1\n')
        match = re.search(r'\bbfd_' + arch + r'_arch\s*(?:\[\])?\s*=\s*\{', text)
        if not match:
            raise ValueError(f'Missing default BFD architecture: {arch}')
        end = closing(text, match.end() - 1)
        values = fields(text[match.end():end])
        if arch == 'spu':
            values = fields(values[0].strip('{} \n'))
        data = dict(word_size=int(values[0]), address_size=int(values[1]),
                    bits_per_byte=int(values[2]), model=string_field(values[6]))
        data['bfd'] = self.reference(origins[text.count('\n', 0, match.start())],
                                     f'bfd_{arch}_arch', source_fields=[compact(v) for v in values])
        return data

    def provenance(self, sources):
        return [dict(path='binutils/' + path,
                     sha256=hashlib.sha256((self.root / path).read_bytes()).hexdigest())
                for path in sorted(sources)]

    def sources(self, arch, records, dimensions):
        sources = {'opcodes/disassemble.c', 'opcodes/configure.in', 'bfd/configure.in',
                   dimensions['bfd']['source'].removeprefix('binutils/')}
        for row in records:
            for key in ('source', 'opcode_source'):
                if key in row:
                    sources.add(row[key].removeprefix('binutils/'))
        for spec in TABLES.get(arch, []):
            sources.add(spec.source)
            sources.update(spec.includes)
        if arch in ('i386', 'l1om', 'k1om'):
            sources.update(('opcodes/i386-dis.c', 'opcodes/i386-opc.h'))
        if arch == 'rs6000':
            sources.update(common.SOURCES['ppc'])
            sources.add('opcodes/ppc-dis.c')
        # Include available descriptor/operand definitions and decoder sources.
        stem = {'mn10200': 'm10200', 'mn10300': 'm10300', 'm68hc12': 'm68hc11'}.get(arch, arch)
        for path in (f'include/opcode/{arch}.h', f'opcodes/{stem}-dis.c',
                     f'opcodes/{stem}-desc.h', f'opcodes/{stem}-opc.h'):
            if (self.root / path).is_file():
                sources.add(path)
        return sources


def dispatcher(root):
    source = (root / 'opcodes/disassemble.c').read_text()
    body = source.split('disassembler (abfd)', 1)[1].split('return disassemble;', 1)[0]
    return sorted(set(re.findall(r'case bfd_arch_(\w+):', body)))


def identifier(name):
    value = re.sub(r'[^A-Za-z0-9_.-]', '_', name)
    return value if value and re.match(r'[A-Za-z_]', value) else 'insn_' + value


def generate(arch, inventory, version):
    records = inventory.instructions(arch)
    if not records:
        raise ValueError(f'No instruction data for {arch}')
    dimensions = inventory.dimensions(arch)
    grouped = defaultdict(list)
    for row in records:
        grouped[row['mnemonic']].append(row)
    bits = sorted({row['encoding_bits'] for row in records if 'encoding_bits' in row})
    profile = dict(family=arch, model=dimensions['model'], version='binutils_' + version,
                   word_size=dimensions['word_size'], address_size=dimensions['address_size'],
                   bits_per_byte=dimensions['bits_per_byte'], byte_order_policy='object_file',
                   instruction_encoding='source_table_defined', register_classes=[],
                   operation_classes=['misc'], instruction_count=len(grouped),
                   encoding_widths=[str(b) for b in bits] or ['source_table_defined'],
                   coverage='source_decoder_families' if arch == 'bfin' else 'source_opcode_inventory',
                   semantics_status='unknown', operand_model='upstream_table_fields')
    binutils = dict(version=version, bfd_arch=arch, generator='generate_binutils_isa.py',
                    scope='source_table_reference_variants', variant_count=len(records),
                    sources=inventory.provenance(inventory.sources(arch, records, dimensions)),
                    bfd=dimensions['bfd'])
    if arch in ('l1om', 'k1om'):
        binutils['backend'] = 'shared_i386_disassembler_64_bit_templates'
    if arch == 'rs6000':
        binutils['dialect'] = 'PPC_OPCODE_POWER'
    text = [MARKER.rstrip(),
            f'arch {arch} {{ word_size = {dimensions["word_size"]}; addr_size = {dimensions["address_size"]}; }}',
            '', 'profile {']
    text += [f'  {key} = {common.render(value)};' for key, value in profile.items()]
    text += [f'  binutils = {common.render(binutils)};', '}', '', 'compiler {',
             '  instruction_selection { strategy = "source_table_lookup"; }',
             '  instruction_scheduling { strategy = "not_described_by_libopcodes"; }',
             '  register_allocation { strategy = "not_described_by_libopcodes"; }',
             '  optimization { legality_model = "unknown_semantics"; }', '}', '']
    used = set()
    for name, variants in sorted(grouped.items()):
        key = identifier(name)
        original = key
        index = 2
        while key in used:
            key = f'{original}_{index}'
            index += 1
        used.add(key)
        encoding = 'ENC_' + key
        widths = {r['encoding_bits'] for r in variants if 'encoding_bits' in r}
        width = str(next(iter(widths))) if len(widths) == 1 and all('encoding_bits' in r for r in variants) else 'variable'
        text += [f'encoding {encoding} {{', f'  width = {width};',
                 '  representation = "upstream_reference";', '}', '',
                 f'op {key} {{ class = misc; encoding = {encoding};',
                 f'  mnemonic = {common.render(name)};', f'  syntax = {common.render(name)};',
                 '  syntax_kind = "mnemonic_or_decoder_family";',
                 '  semantics = "(unknown)";', '  binutils = {', '    variants = [']
        text += ['      ' + common.render(row) + (',' if i + 1 < len(variants) else '')
                 for i, row in enumerate(variants)]
        text += ['    ];', '  };', '}', '']
    entry = dict(file=f'isa/{arch}.isa', arch=arch, family=arch, model=dimensions['model'],
                 version=profile['version'], instruction_count=len(grouped), register_classes=[],
                 semantics=dict(format='s-expression', field='semantics', count=len(grouped), status='unknown'),
                 compiler=['instruction_selection', 'instruction_scheduling', 'register_allocation', 'optimization'],
                 grammar='isa.peg', binutils=dict(bfd_arch=arch, variant_count=len(records)))
    return '\n'.join(text), entry


def outputs(root, infobank, command='cc'):
    inventory = Inventory(root, command)
    architectures = dispatcher(root)
    expected = set(EXISTING) | set(TABLES) | set(CGEN) | {'bfin', 'rx', 'z80', 'i386', 'l1om', 'k1om', 'rs6000'}
    if set(architectures) != expected:
        raise ValueError(f'Dispatcher mapping mismatch: {set(architectures) ^ expected}')
    version = re.search(r'AM_INIT_AUTOMAKE\(bfd,\s*([^\)]+)\)', inventory.read('bfd/configure.in'))[1]
    manifest_path = infobank / 'manifest.json'
    manifest = json.loads(manifest_path.read_text())
    new_entries, generated = {}, {}
    for arch in architectures:
        if arch in EXISTING:
            for name in EXISTING[arch]:
                if not (infobank / 'isa' / (name + '.isa')).is_file():
                    raise ValueError(f'Missing existing description: {name}')
            continue
        text, entry = generate(arch, inventory, version)
        path = infobank / entry['file']
        if path.exists() and not path.read_text().startswith(MARKER):
            raise ValueError(f'Refusing to replace a non-generated ISA description: {path}')
        generated[path] = text
        new_entries[arch] = entry
    # Replace only records owned by this generator; retain all existing records/order.
    manifest['architectures'] = [entry for entry in manifest['architectures'] if entry['arch'] not in new_entries]
    manifest['architectures'].extend(new_entries[name] for name in sorted(new_entries))
    manifest['binutils_coverage'] = dict(version=version, source='binutils/opcodes/disassemble.c',
        sha256=hashlib.sha256((root / 'opcodes/disassemble.c').read_bytes()).hexdigest(),
        architecture_count=len(architectures),
        architectures={name: ['isa/' + stem + '.isa' for stem in EXISTING.get(name, [name])]
                       for name in architectures})
    generated[manifest_path] = json.dumps(manifest, indent=2) + '\n'
    return generated, new_entries


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--binutils', type=Path, default=ROOT / 'binutils')
    parser.add_argument('--infobank', type=Path, default=ROOT / 'yellowstone/infobank')
    parser.add_argument('--cpp', default='cc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated, entries = outputs(args.binutils, args.infobank, args.cpp)
    pending = [(path, text) for path, text in generated.items()
               if not path.exists() or path.read_text() != text]
    for path, text in pending:
        if args.check:
            print(f'STALE: {path}')
        else:
            path.write_text(text)
    print(f'{len(entries)} generated ISA files; '
          f'{sum(e["instruction_count"] for e in entries.values())} mnemonic/decoder groups; '
          f'{sum(e["binutils"]["variant_count"] for e in entries.values())} source variants')
    print(f'{len(pending)} files ' + ('stale' if args.check else 'updated'))
    return int(args.check and bool(pending))


if __name__ == '__main__':
    raise SystemExit(main())
