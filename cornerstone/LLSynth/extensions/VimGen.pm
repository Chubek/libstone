package LLSynth::Extension::VimGen;
use strict;
use warnings;

# Emit Vim regex atoms from the lexer AST. Numeric escapes keep regex and Ex
# command delimiters in user patterns out of generated Vimscript.
sub atom {
    my ($n) = @_;
    my $k = $n->{k};
    if ($k eq 'set') {
        my @bytes = grep { substr($n->{chars}, $_, 1) eq '1' } 0..255;
        if (@bytes == 1) {
            my $ch = chr($bytes[0]);
            return $ch if $ch =~ /[A-Za-z0-9_]/;
            return sprintf '\%%u%04x', $bytes[0];
        }
        my $class = '';
        while (@bytes) {
            my $lo = shift @bytes;
            my $hi = $lo;
            $hi = shift @bytes while @bytes && $bytes[0] == $hi+1;
            $class .= sprintf '\x%02x', $lo;
            $class .= sprintf '-\x%02x', $hi if $lo != $hi;
        }
        return length $class ? "[$class]" : '\%(\)\@!';
    }
    if ($k eq 'seq' || $k eq 'alt') {
        return '\%(' . join(($k eq 'seq' ? '' : '\|'), map { atom($_) } @{$n->{v}}) . '\)';
    }
    my %quantifier = ('*'=>'*', '+'=>'\+', '?'=>'\=');
    my $suffix = $k eq 'rep' ? "\\{$n->{lo},$n->{hi}}" : $quantifier{$k};
    return '\%(' . atom($n->{v}) . '\)' . $suffix;
}

sub literals {
    my ($s) = @_;
    my %literal = map { $_->{literal} => 1 } grep { defined $_->{literal} } @{$s->{tokens}};
    for my $n (LLSynthExtensions::symbols(map { $_->{grammar_ast} } @{$s->{rules}})) {
        $literal{$n->{name}} = 1 if $n->{literal};
    }
    return \%literal;
}

sub render {
    my ($s, $stem) = @_;
    my $syntax = qq{" Generated by LLSynth VimGen\nif exists('b:current_syntax')\n  finish\nendif\nsyntax case match\n};
    my $index = 0;
    for my $tok (reverse grep { $_->{line} && !defined $_->{literal} } @{$s->{tokens}}) {
        my ($ast, $bol, $eol) = main::regex_ast($tok->{regex});
        my $pat = ($bol ? '^' : '') . atom($ast) . ($eol ? '$' : '');
        my $group = 'llsToken' . ++$index;
        my $link = $tok->{type} =~ /^%?(?:U?Int|Float|Number)/i ? 'Number'
                 : $tok->{name} =~ /(?:STRING|STR|CHAR)/i ? 'String' : 'Identifier';
        $syntax .= qq{" $tok->{name}\nsyntax match $group /$pat/\nhighlight default link $group $link\n};
    }
    my $lits = literals($s);
    # At equal start positions Vim prefers the last defined match. Put
    # longer operators after shorter ones so that e.g. == wins over =.
    for my $lit (sort {length($a)<=>length($b) || $a cmp $b} keys %$lits) {
        my $word = $lit =~ /\A[A-Za-z_]\w*\z/;
        my $pat = join '', map { /[A-Za-z0-9_]/ ? $_ : sprintf('\%%U%08x', ord) } split //, $lit;
        $pat = "\\<$pat\\>" if $word;
        my $group = $word ? 'llsKeyword' : 'llsOperator';
        $syntax .= "syntax match $group /$pat/\n";
    }
    $syntax .= "highlight default link llsKeyword Keyword\nhighlight default link llsOperator Operator\nlet b:current_syntax = '$stem'\n";
    my (@opens, @closes);
    for my $pair (['(',')'], ['[',']'], ['{','}']) {
        next unless $lits->{$pair->[0]} && $lits->{$pair->[1]};
        push @opens, "'$pair->[0]'";
        push @closes, "'$pair->[1]'";
    }
    my $indent = <<"VIM";
" Generated by LLSynth VimGen
if exists('b:did_indent')
  finish
endif
let b:did_indent = 1
let s:opens = [@{[join ', ', @opens]}]
let s:closes = [@{[join ', ', @closes]}]
VIM
    $indent .= <<'VIM';
function! s:LLSynthIndent() abort
  let prev = prevnonblank(v:lnum - 1)
  if prev == 0
    return 0
  endif
  let width = indent(prev)
  if index(s:opens, matchstr(getline(prev), '\S\ze\s*$')) >= 0
    let width += shiftwidth()
  endif
  if index(s:closes, matchstr(getline(v:lnum), '\S')) >= 0
    let width -= shiftwidth()
  endif
  return max([width, 0])
endfunction
setlocal indentexpr=<SID>LLSynthIndent()
setlocal indentkeys=o,O,0},0],0)
let b:undo_indent = 'setlocal indentexpr< indentkeys<'
VIM
    return {"syntax/$stem.vim" => $syntax, "indent/$stem.vim" => $indent};
}
1;
