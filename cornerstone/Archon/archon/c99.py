"""Generate a standalone C99 encoder/decoder from Archon's normalized tables."""

import re

from .diagnostics import ArchonError
from .runtime import Target


def generate_codec(db: dict, prefix: str = "archon") -> str:
    """Return a standalone C translation unit for an Archon database.

    The public API uses positional operands, in declaration order. Signed
    immediates are represented by their sign-extended uint64_t bit patterns.
    This codec does not include assembly syntax or execute instruction semantics.
    """
    if not isinstance(prefix, str) or not re.fullmatch(r"[a-z][A-Za-z0-9_]{0,62}", prefix):
        raise ArchonError("C codec prefix must start with a lowercase ASCII letter")
    Target(db)
    registers = db["registers"]
    register_count = registers["count"] if registers is not None else 0
    if register_count.bit_length() > 64:
        raise ArchonError("the C99 codec requires the register count to fit in 64 bits")
    instructions = sorted(db["instructions"], key=lambda inst: inst["name"])
    fields: list[str] = []
    rows: list[str] = []
    for inst in instructions:
        if inst["width"] > 64 or inst["width"] % 8:
            raise ArchonError("the C99 codec requires byte-aligned encodings of up to 64 bits")
        name = inst["name"]
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
            raise ArchonError(f"cannot represent instruction name {name!r} in the C99 codec")
        offset = len(fields)
        by_name = {field["operand"]: field for field in inst["fields"]}
        for operand in inst["operands"]:
            field = by_name[operand["name"]]
            width, lsb = field["width"], field["lsb"]
            if operand["width"] != width or not (0 < width <= 64 and 0 <= lsb <= 64 - width):
                raise ArchonError(f"cannot represent the fields of {name!r} in the C99 codec")
            register_limit = register_count if operand["kind"] == "reg" else 0
            fields.append(
                f"    {{{lsb}, {width}, {int(operand['signed'])}, UINT64_C({register_limit})}},"
            )
        rows.append(
            f'    {{"{name}", UINT64_C(0x{inst["mask"]:x}), UINT64_C(0x{inst["value"]:x}), '
            f'{offset}, {len(inst["operands"])}, {inst["width"] // 8}}},'
        )

    replacements = {
        "@FIELDS@": "\n".join(fields or ["    {0, 0, 0, 0},"]),
        "@ROWS@": "\n".join(rows or ["    {NULL, 0, 0, 0, 0, 0},"]),
        "@COUNT@": str(len(rows)),
        "@LITTLE@": str(int(db["endian"] == "little")),
        "@PREFIX@": prefix,
        "@UPPER@": prefix.upper(),
    }
    return re.sub(r"@[A-Z]+@", lambda match: replacements[match.group()], _CODEC)


_CODEC = r"""/* Generated by Archon. Edit the architecture source, not this file. */
#include <stddef.h>
#include <stdint.h>
#include <string.h>

enum @PREFIX@_status {
    @UPPER@_OK,
    @UPPER@_INVALID_ARGUMENT,
    @UPPER@_UNKNOWN_INSTRUCTION,
    @UPPER@_OPERAND_RANGE,
    @UPPER@_BUFFER_TOO_SMALL
};

struct @PREFIX@_field {
    unsigned lsb, width, is_signed;
    uint64_t register_limit;
};

struct @PREFIX@_instruction {
    const char *name;
    uint64_t mask, value;
    size_t first_field, operand_count, byte_count;
};

static const struct @PREFIX@_field @PREFIX@_fields[] = {
@FIELDS@
};

static const struct @PREFIX@_instruction @PREFIX@_instructions[] = {
@ROWS@
};

static const size_t @PREFIX@_count = @COUNT@;

static uint64_t @PREFIX@_low_mask(unsigned width) {
    return UINT64_MAX >> (64u - width);
}

static uint64_t @PREFIX@_sign_extend(uint64_t value, unsigned width) {
    uint64_t top = UINT64_C(1) << (width - 1u);
    return (value ^ top) - top;
}

static size_t @PREFIX@_byte_shift(size_t pos, size_t count) {
    return 8u * (@LITTLE@ ? pos : count - 1u - pos);
}

/* Writes exactly the instruction size on success and does not modify out on error. */
enum @PREFIX@_status @PREFIX@_encode(const char *name, const uint64_t *operands,
        size_t operand_count, uint8_t *out, size_t out_capacity, size_t *out_size) {
    const struct @PREFIX@_instruction *inst;
    uint64_t word;
    size_t i;
    if (!name || !out_size || (operand_count && !operands) || (out_capacity && !out))
        return @UPPER@_INVALID_ARGUMENT;
    for (i = 0; i < @PREFIX@_count; ++i)
        if (strcmp(name, @PREFIX@_instructions[i].name) == 0)
            break;
    if (i == @PREFIX@_count)
        return @UPPER@_UNKNOWN_INSTRUCTION;
    inst = &@PREFIX@_instructions[i];
    if (operand_count != inst->operand_count)
        return @UPPER@_INVALID_ARGUMENT;
    if (out_capacity < inst->byte_count)
        return @UPPER@_BUFFER_TOO_SMALL;
    word = inst->value;
    for (i = 0; i < operand_count; ++i) {
        const struct @PREFIX@_field *field = &@PREFIX@_fields[inst->first_field + i];
        uint64_t value = operands[i], low = value & @PREFIX@_low_mask(field->width);
        if ((field->register_limit && value >= field->register_limit) ||
                value != (field->is_signed ? @PREFIX@_sign_extend(low, field->width) : low))
            return @UPPER@_OPERAND_RANGE;
        word |= low << field->lsb;
    }
    for (i = 0; i < inst->byte_count; ++i)
        out[i] = (uint8_t)(word >> @PREFIX@_byte_shift(i, inst->byte_count));
    *out_size = inst->byte_count;
    return @UPPER@_OK;
}

/* Decodes exactly one instruction; the returned name points to static storage. */
enum @PREFIX@_status @PREFIX@_decode(const uint8_t *data, size_t data_len,
        const char **name, uint64_t *operands, size_t operand_capacity, size_t *operand_count) {
    const struct @PREFIX@_instruction *inst = NULL;
    uint64_t word = 0;
    size_t i;
    if (!data || !name || !operand_count || (operand_capacity && !operands))
        return @UPPER@_INVALID_ARGUMENT;
    if (data_len == 0 || data_len > 8)
        return @UPPER@_UNKNOWN_INSTRUCTION;
    for (i = 0; i < data_len; ++i)
        word |= (uint64_t)data[i] << @PREFIX@_byte_shift(i, data_len);
    for (i = 0; i < @PREFIX@_count; ++i) {
        const struct @PREFIX@_instruction *candidate = &@PREFIX@_instructions[i];
        if (candidate->byte_count == data_len && (word & candidate->mask) == candidate->value) {
            inst = candidate;
            break;
        }
    }
    if (!inst)
        return @UPPER@_UNKNOWN_INSTRUCTION;
    if (operand_capacity < inst->operand_count)
        return @UPPER@_BUFFER_TOO_SMALL;
    for (i = 0; i < inst->operand_count; ++i) {
        const struct @PREFIX@_field *field = &@PREFIX@_fields[inst->first_field + i];
        uint64_t low = (word >> field->lsb) & @PREFIX@_low_mask(field->width);
        if (field->register_limit && low >= field->register_limit)
            return @UPPER@_OPERAND_RANGE;
    }
    for (i = 0; i < inst->operand_count; ++i) {
        const struct @PREFIX@_field *field = &@PREFIX@_fields[inst->first_field + i];
        uint64_t low = (word >> field->lsb) & @PREFIX@_low_mask(field->width);
        operands[i] = field->is_signed ? @PREFIX@_sign_extend(low, field->width) : low;
    }
    *name = inst->name;
    *operand_count = inst->operand_count;
    return @UPPER@_OK;
}
"""
