"""Emit the standalone, data-only source-to-ANF front end."""

from pathlib import Path

from ..diagnostics import ArchonError


STAGE_ORDER = 5


def _source_literal(name: str, source: bytes) -> str:
    # Adjacent byte literals copy the full upstream text, including line
    # endings, POD, and Perl __DATA__ sections, without escaping ambiguity.
    return f"\n{name} = (\n" + "".join(
        f"    {line!r}\n" for line in source.splitlines(keepends=True)
    ) + ")\n"


def emit(context: dict) -> dict[str, str]:
    """Embed both canonical Perl tools; the result needs no Archon checkout."""
    here = Path(__file__).resolve().parent
    cornerstone = here.parents[2]
    try:
        asdl = (cornerstone / "ASDL/scripts/asdl.pl").read_bytes()
        aurocks = (cornerstone / "Aurocks/scripts/aurocks.pl").read_bytes()
        adapter = (here / "_translate_aurocks.pl").read_bytes()
        runtime = (here / "_translate_runtime.py").read_text(encoding="utf-8")
        license_text = (cornerstone.parent / "LICENSE").read_text(encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        raise ArchonError(f"cannot embed Translate.py sources: {exc}") from exc
    if not aurocks.rstrip().endswith(b"\nmain();"):
        raise ArchonError("Translate.py's data adapter needs Aurocks' standalone main()")
    notice = "\n".join("# " + line if line else "#" for line in license_text.splitlines())
    return {"Translate.py": (
        "#!/usr/bin/env python3\n"
        "# Generated by Archon. Includes the canonical sources of:\n"
        "#   ASDL (cornerstone/ASDL/scripts/asdl.pl)\n"
        "#   Aurocks (cornerstone/Aurocks/scripts/aurocks.pl)\n"
        + notice + "\n\n"
        + runtime + "\n"
        + f"\nIR_REPRESENTATION = {context['ir']!r}\n"
        + _source_literal("ASDL_SOURCE", asdl)
        + _source_literal("AUROCKS_SOURCE", aurocks)
        + _source_literal("AUROCKS_DATA_ADAPTER", adapter)
        + '\nif __name__ == "__main__":\n'
          '    raise SystemExit(main(IR_REPRESENTATION, ASDL_SOURCE, AUROCKS_SOURCE,\n'
          '                          AUROCKS_DATA_ADAPTER))\n'
    )}
