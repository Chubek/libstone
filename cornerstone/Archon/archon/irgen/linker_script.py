"""Generate the standalone link wrapper (not part of the generated C runtime)."""

from __future__ import annotations

from collections.abc import Mapping
from shlex import quote

from ..diagnostics import ArchonError


NAME = "linker-script"
STAGE_ORDER = 1700

_PROGRAMS = {
    "gnu": "ld.bfd",
    "gold": "ld.gold",
    "mold": "mold",
    "lld": "ld.lld",
    "yld": "qobjld",
}
_GCC_LINKERS = {"gnu": "bfd", "gold": "gold", "mold": "mold"}


def _path(options: Mapping[str, object], name: str, default: str = "") -> str:
    if name not in options:
        return default
    value = options[name]
    if not isinstance(value, str) or not value or "\0" in value:
        raise ArchonError(f"generation option {name!r} must be a nonempty path without NULs")
    return value


def _program(options: Mapping[str, object], name: str, default: str) -> str:
    program = _path(options, name, default)
    if program.startswith("-"):
        raise ArchonError(f"generation option {name!r} must not start with '-' (use './' for paths)")
    return program


def emit(context: Mapping[str, object]) -> dict[str, str]:
    options = context.get("options", {})
    if not isinstance(options, Mapping):
        raise ArchonError("linker generation options must be an object")
    provider = options.get("linker", "gnu")
    if not isinstance(provider, str) or provider not in _PROGRAMS:
        raise ArchonError(f"generation option 'linker' must be one of: {', '.join(_PROGRAMS)}")
    lto = options.get("lto", False)
    if type(lto) is not bool:
        raise ArchonError("generation option 'lto' must be a boolean")
    layout = _path(options, "linker_script")
    if layout.lower().endswith(".lua") and (provider != "yld" or not layout.endswith(".lua")):
        raise ArchonError(
            "generation option 'linker_script': Lua layouts require linker 'yld' "
            "and the lowercase .lua suffix"
        )

    gcc_linker = _GCC_LINKERS.get(provider) if lto else None
    llvm_lto = provider == "lld" and lto
    yld_lto = provider == "yld" and lto
    if gcc_linker:
        if "linker_program" in options:
            raise ArchonError(
                "generation option 'linker_program' cannot select a GCC LTO linker; "
                "configure the toolchain with 'lto_driver' instead"
            )
        program = _program(options, "lto_driver", "gcc")
    else:
        if "lto_driver" in options:
            raise ArchonError("generation option 'lto_driver' requires LTO with gnu, gold or mold")
        program = _program(options, "linker_program", _PROGRAMS[provider])

    sections = [
        _HEADER,
        f"provider={quote(provider)}\nprogram={quote(program)}\nlayout={quote(layout)}\n"
        f"lto_ir={'gcc' if gcc_linker else 'llvm' if llvm_lto else 'none'}\n",
        _PARSE,
        _INPUTS,
    ]
    if gcc_linker:
        sections.extend((f"fuse_ld=-fuse-ld={gcc_linker}\n", _GCC_PREFLIGHT))
    if yld_lto:
        sections.append(_YLD_LTO_PATH)
    sections.append(_STAGE_OUTPUT)
    if gcc_linker:
        sections.append(_GCC_ARGS)
    else:
        sections.append(_DIRECT_ARGS)
        if provider == "lld":
            level = "--lto-O2" if lto else "--lto-O0 --lto-CGO0"
            sections.append(f'set -- {level} "$@"\n')
        if yld_lto:
            sections.append('set -- --lto-script "$lto_script" "$@"\n')
    sections.append(_LINK)

    outputs = {"Linker.sh": "".join(sections)}
    if yld_lto:
        outputs["LTO.lua"] = _LTO_LUA
    return outputs


_HEADER = """#!/bin/sh
# Generated by Archon. Use trusted tools, link inputs and layout scripts.
# Layout, input, output and configured tool paths are relative to the calling
# working directory. A bare tool name is looked up on PATH at link time.
# Layout scripts are passed to the selected linker, not run by this shell.
# Requires od, mktemp, mv and rm; ELF inputs also require readelf and grep.
"""

_PARSE = r'''
usage() {
    printf '%s\n' 'usage: sh Linker.sh -o OUTPUT [--script PATH] [--entry SYMBOL] [--] INPUT...'
}

fail() {
    printf '%s\n' "Linker.sh: $1" >&2
    exit 2
}

need() {
    if ! command -v "$1" >/dev/null 2>&1; then
        printf '%s\n' "Linker.sh: $provider requires executable '$1' (not found)" >&2
        exit 127
    fi
}

protect_output() {
    if [ "$output" = "$1" ] || [ "$output" -ef "$1" ]; then
        fail "output aliases $2 '$1'"
    fi
}

output=
entry=
override=no
default_layout=$layout
while [ "$#" -gt 0 ]; do
    case $1 in
        -o)
            [ "$#" -ge 2 ] && [ -n "$2" ] || fail '-o needs an output path'
            [ -z "$output" ] || fail 'duplicate -o'
            output=$2
            shift 2
            ;;
        --script)
            [ "$#" -ge 2 ] && [ -n "$2" ] || fail '--script needs a layout path'
            [ "$override" = no ] || fail 'duplicate --script'
            override=yes
            layout=$2
            shift 2
            ;;
        -e|--entry)
            [ "$#" -ge 2 ] && [ -n "$2" ] || fail '--entry needs a symbol'
            [ -z "$entry" ] || fail 'duplicate --entry'
            entry=$2
            shift 2
            ;;
        -h|--help) usage; exit 0 ;;
        --) shift; break ;;
        -*) fail "unknown option '$1' (use -- before input paths starting with '-')" ;;
        *) break ;;
    esac
done
[ -n "$output" ] || fail 'missing -o OUTPUT'
[ "$#" -gt 0 ] || fail 'no input files'

# Prefix option-like paths, including @response files, before handing them on.
case $layout in -*|@*) layout=./$layout ;; esac
case $output in -*|@*) output=./$output ;; esac
case $layout in
    *.lua) [ "$provider" = yld ] || fail "layout scripts ending in .lua require linker 'yld'" ;;
    *.[lL][uU][aA]) fail 'Lua layout scripts must use the lowercase .lua suffix' ;;
esac
if [ -n "$layout" ]; then
    [ -f "$layout" ] && [ -r "$layout" ] || fail "cannot read layout script '$layout'"
    protect_output "$layout" 'layout script'
fi
if [ "$override" = yes ] && [ -n "$default_layout" ]; then
    protect_output "$default_layout" 'configured layout script'
fi
protect_output "$0" 'wrapper'
need "$program"
case $program in
    */*) tool=$program ;;
    *) tool=$(command -v "$program") ;;
esac
case $tool in */*) ;; *) tool=./$tool ;; esac
[ -f "$tool" ] && [ -x "$tool" ] || fail "'$program' is not an executable file"
protect_output "$tool" 'selected tool'
'''

_INPUTS = r'''
need od
has_ir=no
checked_elf_tools=no
# Rotate the positional parameters once to replace input paths without splitting.
for input in "$@"; do
    case $input in -*|@*) input=./$input ;; esac
    [ -f "$input" ] && [ -r "$input" ] || fail "cannot read input file '$input'"
    protect_output "$input" 'input'
    magic=$(LC_ALL=C od -A n -N 4 -t x1 < "$input") || fail "cannot inspect '$input'"
    case $magic in
        *'42 43 c0 de'*|*'de c0 17 0b'*)
            [ "$provider" = lld ] || fail "$provider cannot link standalone LLVM bitcode '$input'"
            has_ir=yes
            ;;
        *'7f 45 4c 46'*)
            if [ "$checked_elf_tools" = no ]; then
                need readelf
                need grep
                checked_elf_tools=yes
            fi
            # Direct linkers can appear to succeed while ignoring GCC IR.
            # Look for the GCC LTO header in standalone ELF input sections.
            sections=$(LC_ALL=C readelf -W -S -- "$input") || fail "cannot inspect ELF input '$input'"
            if printf '%s\n' "$sections" |
                LC_ALL=C grep -Eq '^[[:space:]]*\[[^]]+\][[:space:]]+\.gnu\.lto_\.lto(\.[^[:space:]]+)?[[:space:]]'; then
                [ "$lto_ir" = gcc ] ||
                    fail "$provider cannot use GCC GIMPLE '$input' without a GCC LTO link"
                has_ir=yes
            fi
            ;;
    esac
    shift
    if [ "$lto_ir" = gcc ]; then
        # All INPUT values go to the linker, not to GCC's source compiler.
        set -- "$@" -Xlinker "$input"
    else
        set -- "$@" "$input"
    fi
done
# Archive members are not a sufficient LTO preflight: the linker might not
# extract them. The selected tool validates the actual IR and input formats.
if [ "$has_ir" = no ]; then
    case $lto_ir in
        gcc) fail 'LTO needs a standalone GCC GIMPLE (-flto) input' ;;
        llvm) fail 'LTO needs a standalone LLVM bitcode (-flto) input' ;;
    esac
fi
'''

_GCC_PREFLIGHT = r'''
if ! plugin=$("$tool" -print-file-name=liblto_plugin.so) ||
    [ "$plugin" = liblto_plugin.so ] || [ ! -f "$plugin" ] || [ ! -r "$plugin" ]; then
    fail "GCC LTO driver '$program' must provide a readable liblto_plugin.so"
fi
if ! wrapper=$("$tool" -print-prog-name=lto-wrapper) ||
    [ "$wrapper" = lto-wrapper ] || [ ! -f "$wrapper" ] || [ ! -x "$wrapper" ]; then
    fail "GCC LTO driver '$program' must provide an executable lto-wrapper"
fi
protect_output "$plugin" 'GCC LTO plugin'
protect_output "$wrapper" 'GCC LTO wrapper'
if gcc_linker=$("$tool" "$fuse_ld" -print-prog-name=ld); then
    case $gcc_linker in
        */*) protect_output "$gcc_linker" 'GCC linker' ;;
        ''|-*) ;;
        *)
            if gcc_linker=$(command -v "$gcc_linker"); then
                protect_output "$gcc_linker" 'GCC linker'
            fi
            ;;
    esac
fi
'''

_YLD_LTO_PATH = r'''
# Use the invoked wrapper's sibling, regardless of the working directory.
case $0 in
    */*) lto_script=${0%/*}/LTO.lua ;;
    *) lto_script=./LTO.lua ;;
esac
case $lto_script in -*|@*) lto_script=./$lto_script ;; esac
[ -f "$lto_script" ] && [ -r "$lto_script" ] || fail "cannot read LTO policy '$lto_script'"
protect_output "$lto_script" 'LTO policy'
'''

_STAGE_OUTPUT = r'''
# Link in a private directory on the destination filesystem. Do not let a
# failed linker truncate or remove a previous output.
case $output in
    */) fail 'output path must name a file' ;;
    */*) outdir=${output%/*}; outdir=${outdir:-/} ;;
    *) outdir=. ;;
esac
check_destination() {
    if [ -e "$output" ] && [ ! -f "$output" ]; then
        fail "output is not a regular file: '$output'"
    fi
}
check_destination
need mktemp
need mv
need rm
tempdir=$(mktemp -d "${outdir%/}/.archon-link.XXXXXXXX") ||
    fail "cannot stage output '$output'"
staged=$tempdir/${output##*/}
trap 'rm -rf "$tempdir"' 0
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM
'''

_DIRECT_ARGS = r'''
set -- -o "$staged" "$@"
if [ -n "$entry" ]; then set -- "--entry=$entry" "$@"; fi
if [ -n "$layout" ]; then set -- -T "$layout" "$@"; fi
'''

_GCC_ARGS = r'''
set -- "$fuse_ld" -O2 -flto -fuse-linker-plugin -nostdlib -static -no-pie -o "$staged" "$@"
if [ -n "$entry" ]; then set -- -Xlinker "--entry=$entry" "$@"; fi
if [ -n "$layout" ]; then set -- -Xlinker -T -Xlinker "$layout" "$@"; fi
'''

_LINK = r'''
if "$tool" "$@"; then
    [ -f "$staged" ] && [ ! -L "$staged" ] ||
        fail "'$program' reported success without producing '$output'"
    check_destination
    mv -f "$staged" "$output" || fail "cannot publish output '$output'"
else
    rc=$?
    printf '%s\n' "Linker.sh: $provider link failed (exit $rc)" >&2
    exit "$rc"
fi
'''

_LTO_LUA = """-- Generated by Archon for qobjld --lto-script (native static ELF only).
-- Keep default roots and their transitive relocation dependencies.
function optimize(link)
    return { gc_sections = true, keep = {} }
end
"""
