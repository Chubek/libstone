"""Generate the representation-neutral cross-stage verifier.

The generated verifier deliberately does not include any of the stage-specific
X-macro files.  A stage decoder exposes its decoded data through the flat
descriptors in ``Verify.h``; this keeps the verifier usable with every IR
backend and lets independently generated stages evolve their macro spelling
without coupling it to this module.
"""

