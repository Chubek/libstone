"""Generate the bounded external Oracle protocol runtime.

The Oracle is deliberately an optional pipeline facility.  Generation is on by
default, but an explicit JSON option ``{"oracle": false}`` removes the stage
entirely.  At run time the generated client is inert unless the caller supplies
an AF_UNIX socket path.

Artifacts travel through a named POSIX shared-memory object rather than through
the socket.  The socket carries only a versioned, length-delimited request and
response.  Analysis results use a separate X-macro sidecar, so existing ``.i``
consumers never encounter Oracle records they do not understand.
"""

from __future__ import annotations

from collections.abc import Mapping


NAME = "oracle"
ALIASES = ("external-oracle", "analysis-oracle")
STAGE_ORDER = 40


def oracle_is_enabled(context: object = None) -> bool:
    """Return whether *context* enables Oracle generation.

    Only the explicit Boolean value ``False`` disables the stage.  This keeps
    direct emitter use and older generation contexts enabled by default while
    matching the JSON-compatible context contract used by :mod:`archon.irgen`.
    """

    options: object = None
    if isinstance(context, Mapping):
        options = context.get("options")
    elif context is not None:
        options = getattr(context, "options", None)
    return not (isinstance(options, Mapping) and options.get("oracle") is False)


def emit(context: object = None) -> dict[str, str]:
    """Emit the strict-C99 Oracle client/server runtime."""

    if not oracle_is_enabled(context):
        return {}
    return {"Oracle.h": _HEADER, "Oracle.c": _SOURCE}


