"""Generate Archon's small, typed A-normal-form IR runtime.

The representation is deliberately independent of an architecture.  A
``Program.i`` file is an X-macro description of a program; the generated
``IR.c`` decodes it through the public builder API instead of relying on C
initialiser layout.  This keeps malformed input diagnosable and gives later
pipeline stages one checked in-memory representation.
"""

from __future__ import annotations

from typing import Any


NAME = "anf"
ALIASES = ("anormal", "a-normal", "a-normal-form")


def emit_ir(context: Any) -> dict[str, str]:
    """Return the strict-C99 ANF implementation.

    ``context`` is accepted for the common representation plug-in contract.
    ANF itself is target independent, so no context fields are required.
    """

    del context
    return {"IR.h": _HEADER, "IR.c": _SOURCE}


# Some embedders use ``emit`` uniformly for representations and stages.
def emit(context: Any) -> dict[str, str]:
    return emit_ir(context)


