"""Generate the public, argv-free C embedding facade.

The facade deliberately delegates compilation work to ``Pipeline.c`` and final
assembly validation to ``Emitter.c``.  It owns only per-invocation defaults,
bounded result reporting, and the fixed intermediate-artifact retention policy
that otherwise lives in the generated CLI driver.
"""

from __future__ import annotations

from collections.abc import Mapping

from ..diagnostics import ArchonError


NAME = "embedding"
ALIASES = ("embed", "c-embedding")
STAGE_ORDER = 1100


_INTERMEDIATES = (
    "Rewritten.i",
    "MIR.i",
    "Selected.i",
    "InstrMap.i",
    "Scheduled.i",
    "RegMap.i",
    "Regallocated.i",
)

_ORACLE_SIDECARS = (
    "Rewritten.oracle.i",
    "MIR.oracle.i",
    "Selected.oracle.i",
    "InstrMap.oracle.i",
    "Scheduled.oracle.i",
    "RegMap.oracle.i",
    "Regallocated.oracle.i",
)


def _oracle_enabled(context: object) -> bool:
    if not isinstance(context, Mapping):
        return True
    options = context.get("options", {})
    if options is None:
        options = {}
    if not isinstance(options, Mapping):
        raise ArchonError("embedding options must be an object")
    enabled = options.get("oracle", True)
    if type(enabled) is not bool:
        raise ArchonError("embedding option 'oracle' must be boolean")
    return enabled


def _artifact_rows(oracle_enabled: bool) -> str:
    names = _INTERMEDIATES + (
        _ORACLE_SIDECARS if oracle_enabled else ()
    )
    return "\n".join(f'    "{name}",' for name in names)


def emit(context: object) -> dict[str, str]:
    oracle_enabled = _oracle_enabled(context)
    options = (context.get("options") or {}) if isinstance(context, Mapping) else {}
    oracle_option_field = (
        "    const ArchonOracleOptions *oracle;\n"
        if oracle_enabled
        else ""
    )
    oracle_assignments = (
        "    emitter.oracle = options->oracle;\n"
        "    pipeline.oracle = options->oracle;\n"
        if oracle_enabled
        else ""
    )
    header = _HEADER.replace(
        "@ORACLE_OPTION_FIELD@", oracle_option_field
    )
    source = (
        _SOURCE.replace(
            "@INTERMEDIATE_ARTIFACTS@", _artifact_rows(oracle_enabled)
        )
        .replace("@ORACLE_ASSIGNMENTS@", oracle_assignments)
        .replace(
            "@DEFAULT_DIALECT@",
            "ARCHON_EMBED_DIALECT_ARCHON" if options.get("assembler") == "archon"
            else "ARCHON_EMBED_DIALECT_GAS",
        )
    )
    return {
        "ArchonEmbed.h": header,
        "ArchonEmbed.c": source,
    }


_HEADER = r'''/* Generated by Archon: public C embedding facade. */
#ifndef ARCHON_GENERATED_EMBED_H
#define ARCHON_GENERATED_EMBED_H

#include "Pipeline.h"

#include <stddef.h>

#ifdef __cplusplus
extern "C" {
#endif

#define ARCHON_EMBED_API_VERSION 0x00010000UL
#define ARCHON_EMBED_MAX_DIAGNOSTIC_BYTES 511u

/*
 * These aliases keep embedding clients in one namespace while preserving the
 * exact stage, rewrite, and dialect contracts implemented by Pipeline.c and
 * Emitter.c.
 */
typedef ArchonPipelineStage ArchonEmbedStage;
#define ARCHON_EMBED_STAGE_DECODE ARCHON_PIPELINE_DECODE
#define ARCHON_EMBED_STAGE_REWRITE ARCHON_PIPELINE_REWRITE
#define ARCHON_EMBED_STAGE_SCHEDULE ARCHON_PIPELINE_SCHEDULE
#define ARCHON_EMBED_STAGE_ISEL ARCHON_PIPELINE_ISEL
#define ARCHON_EMBED_STAGE_ISCHED ARCHON_PIPELINE_ISCHED
#define ARCHON_EMBED_STAGE_REGALLOC ARCHON_PIPELINE_REGALLOC
#define ARCHON_EMBED_STAGE_EMIT ARCHON_PIPELINE_EMIT

typedef ArchonPipelineRewrite ArchonEmbedRewrite;
#define ARCHON_EMBED_REWRITE_CONVENTIONAL \
    ARCHON_PIPELINE_REWRITE_CONVENTIONAL
#define ARCHON_EMBED_REWRITE_EGRAPH ARCHON_PIPELINE_REWRITE_EGRAPH

typedef Emitter_Dialect ArchonEmbedDialect;
#define ARCHON_EMBED_DIALECT_GAS EMITTER_DIALECT_GAS
#define ARCHON_EMBED_DIALECT_SANDSTONE EMITTER_DIALECT_SANDSTONE
#define ARCHON_EMBED_DIALECT_ARCHON EMITTER_DIALECT_ARCHON

typedef enum ArchonEmbedArtifactPolicy {
    /*
     * Both policies remove stale fixed-name intermediates before a run.
     * DISCARD also removes intermediates produced by the invocation.
     * Neither policy removes Program.i or a successful assembly output.
     */
    ARCHON_EMBED_ARTIFACTS_DISCARD = 0,
    ARCHON_EMBED_ARTIFACTS_RETAIN
} ArchonEmbedArtifactPolicy;

typedef enum ArchonEmbedStatus {
    ARCHON_EMBED_STATUS_OK = 0,
    ARCHON_EMBED_STATUS_INVALID_ARGUMENT,
    ARCHON_EMBED_STATUS_PIPELINE_ERROR,
    ARCHON_EMBED_STATUS_CLEANUP_ERROR
} ArchonEmbedStatus;

typedef struct ArchonEmbedOptions {
    ArchonEmbedStage stop_after;
    ArchonEmbedRewrite rewrite;
    ArchonEmbedDialect dialect;
    const char *output_path; /* NULL selects the dialect's default path. */
    const Emitter_Hooks *emitter_hooks;
    ArchonEmbedArtifactPolicy artifact_policy;
@ORACLE_OPTION_FIELD@
} ArchonEmbedOptions;

typedef struct ArchonEmbedResult {
    ArchonEmbedStatus status;
    ArchonPipelineStatus pipeline_status;
    ArchonEmbedStage stage;
    unsigned stage_valid;
    Emitter_Status emitter_status;
    unsigned emitter_artifact_line;
    size_t artifacts_removed;
    unsigned artifacts_retained;
    unsigned output_emitted;
    char diagnostic[ARCHON_EMBED_MAX_DIAGNOSTIC_BYTES + 1u];
} ArchonEmbedResult;

void archon_embed_options_init(ArchonEmbedOptions *options);
void archon_embed_result_init(ArchonEmbedResult *result);
const char *archon_embed_status_string(ArchonEmbedStatus status);

/*
 * Run the embedded, compile-time-selected Program.i.  The function does not
 * inspect argv or the environment, does not call Driver.c, and writes no
 * diagnostics to a process stream.  All in-memory mutable state is
 * invocation-local.  Because pipeline intermediates have fixed names, callers
 * must not overlap invocations in the same working directory.
 */
ArchonEmbedStatus archon_embed_run(
    const ArchonEmbedOptions *options,
    ArchonEmbedResult *result);

/*
 * Remove only generated fixed-name intermediate artifacts (and generated
 * sidecars when that facility exists).  Program.i and assembly outputs are
 * never removed.  Passing NULL for result is permitted.
 */
ArchonEmbedStatus archon_embed_cleanup_intermediates(
    ArchonEmbedResult *result);

#ifdef __cplusplus
}
#endif

#endif
'''


_SOURCE = r'''/* Generated by Archon: strict ISO C11 embedding facade. */
#include "ArchonEmbed.h"

#include <errno.h>
#include <stdarg.h>
#include <stdio.h>
#include <string.h>

static const char *const AE_intermediate_artifacts[] = {
@INTERMEDIATE_ARTIFACTS@
};

static void AE_diagnostic(
        ArchonEmbedResult *result, const char *format, ...) {
    va_list arguments;
    if (result == NULL || format == NULL)
        return;
    va_start(arguments, format);
    (void)vsnprintf(
        result->diagnostic, sizeof result->diagnostic, format, arguments);
    va_end(arguments);
    result->diagnostic[sizeof result->diagnostic - 1u] = '\0';
}

static void AE_append_diagnostic(
        ArchonEmbedResult *result, const char *text) {
    size_t used;
    if (result == NULL || text == NULL || text[0] == '\0')
        return;
    used = strlen(result->diagnostic);
    if (used >= sizeof result->diagnostic - 1u)
        return;
    (void)snprintf(
        result->diagnostic + used,
        sizeof result->diagnostic - used,
        "%s%s", used != 0u ? "; " : "", text);
    result->diagnostic[sizeof result->diagnostic - 1u] = '\0';
}

void archon_embed_options_init(ArchonEmbedOptions *options) {
    if (options != NULL) {
        memset(options, 0, sizeof *options);
        options->stop_after = ARCHON_EMBED_STAGE_EMIT;
        options->rewrite = ARCHON_EMBED_REWRITE_CONVENTIONAL;
        options->dialect = @DEFAULT_DIALECT@;
        options->artifact_policy = ARCHON_EMBED_ARTIFACTS_DISCARD;
    }
}

void archon_embed_result_init(ArchonEmbedResult *result) {
    if (result != NULL) {
        memset(result, 0, sizeof *result);
        result->status = ARCHON_EMBED_STATUS_OK;
        result->pipeline_status = ARCHON_PIPELINE_STATUS_OK;
        result->emitter_status = EMITTER_STATUS_OK;
    }
}

const char *archon_embed_status_string(ArchonEmbedStatus status) {
    switch (status) {
    case ARCHON_EMBED_STATUS_OK:
        return "ok";
    case ARCHON_EMBED_STATUS_INVALID_ARGUMENT:
        return "invalid argument";
    case ARCHON_EMBED_STATUS_PIPELINE_ERROR:
        return "pipeline error";
    case ARCHON_EMBED_STATUS_CLEANUP_ERROR:
        return "artifact cleanup error";
    }
    return "unknown embedding status";
}

static int AE_reserved_output(const char *path) {
    size_t index;
    if (path == NULL)
        return 0;
    if (strcmp(path, "Program.i") == 0)
        return 1;
    for (index = 0u;
            index < sizeof AE_intermediate_artifacts /
                        sizeof AE_intermediate_artifacts[0];
            ++index)
        if (strcmp(path, AE_intermediate_artifacts[index]) == 0)
            return 1;
    return 0;
}

static int AE_options_valid(
        const ArchonEmbedOptions *options,
        ArchonEmbedResult *result) {
    if (options == NULL) {
        AE_diagnostic(result, "embedding options are required");
        return 0;
    }
    if (options->stop_after < ARCHON_EMBED_STAGE_DECODE ||
            options->stop_after > ARCHON_EMBED_STAGE_EMIT) {
        AE_diagnostic(result, "invalid pipeline stopping stage");
        return 0;
    }
    if (options->rewrite != ARCHON_EMBED_REWRITE_CONVENTIONAL &&
            options->rewrite != ARCHON_EMBED_REWRITE_EGRAPH) {
        AE_diagnostic(result, "invalid rewrite mode");
        return 0;
    }
    if (options->dialect != ARCHON_EMBED_DIALECT_GAS &&
            options->dialect != ARCHON_EMBED_DIALECT_SANDSTONE &&
            options->dialect != ARCHON_EMBED_DIALECT_ARCHON) {
        AE_diagnostic(result, "invalid assembly dialect");
        return 0;
    }
    if (options->artifact_policy != ARCHON_EMBED_ARTIFACTS_DISCARD &&
            options->artifact_policy != ARCHON_EMBED_ARTIFACTS_RETAIN) {
        AE_diagnostic(result, "invalid artifact retention policy");
        return 0;
    }
    if (options->output_path != NULL &&
            (options->output_path[0] == '\0' ||
             AE_reserved_output(options->output_path))) {
        AE_diagnostic(
            result, "output path is empty or reserved by the pipeline");
        return 0;
    }
    return 1;
}

static int AE_cleanup(
        size_t *removed, char *diagnostic, size_t diagnostic_capacity) {
    size_t index;
    int success = 1;
    if (diagnostic != NULL && diagnostic_capacity != 0u)
        diagnostic[0] = '\0';
    for (index = 0u;
            index < sizeof AE_intermediate_artifacts /
                        sizeof AE_intermediate_artifacts[0];
            ++index) {
        if (remove(AE_intermediate_artifacts[index]) == 0) {
            if (removed != NULL)
                ++*removed;
        } else if (errno != ENOENT) {
            int error = errno;
            success = 0;
            if (diagnostic != NULL && diagnostic_capacity != 0u &&
                    diagnostic[0] == '\0') {
                (void)snprintf(
                    diagnostic, diagnostic_capacity,
                    "cannot remove %s (error %d)",
                    AE_intermediate_artifacts[index], error);
                diagnostic[diagnostic_capacity - 1u] = '\0';
            }
        }
    }
    return success;
}

ArchonEmbedStatus archon_embed_cleanup_intermediates(
        ArchonEmbedResult *result) {
    ArchonEmbedResult local_result;
    char diagnostic[ARCHON_EMBED_MAX_DIAGNOSTIC_BYTES + 1u];
    if (result == NULL)
        result = &local_result;
    archon_embed_result_init(result);
    if (!AE_cleanup(
            &result->artifacts_removed,
            diagnostic, sizeof diagnostic)) {
        result->status = ARCHON_EMBED_STATUS_CLEANUP_ERROR;
        AE_diagnostic(result, "%s", diagnostic);
    }
    return result->status;
}

ArchonEmbedStatus archon_embed_run(
        const ArchonEmbedOptions *options,
        ArchonEmbedResult *result) {
    ArchonEmbedResult local_result;
    ArchonPipelineOptions pipeline;
    ArchonPipelineResult pipeline_result;
    Emitter_Options emitter;
    char cleanup_diagnostic[ARCHON_EMBED_MAX_DIAGNOSTIC_BYTES + 1u];
    int cleanup_success;
    if (result == NULL)
        result = &local_result;
    archon_embed_result_init(result);
    if (!AE_options_valid(options, result)) {
        result->status = ARCHON_EMBED_STATUS_INVALID_ARGUMENT;
        result->pipeline_status = ARCHON_PIPELINE_STATUS_INVALID_ARGUMENT;
        return result->status;
    }

    cleanup_success = AE_cleanup(
        &result->artifacts_removed,
        cleanup_diagnostic, sizeof cleanup_diagnostic);
    if (!cleanup_success) {
        result->status = ARCHON_EMBED_STATUS_CLEANUP_ERROR;
        AE_diagnostic(result, "%s", cleanup_diagnostic);
        return result->status;
    }

    memset(&emitter, 0, sizeof emitter);
    emitter.dialect = options->dialect;
    emitter.output_path = options->output_path;
    emitter.hooks = options->emitter_hooks;
    emitter.diagnostics = NULL;

    archon_pipeline_options_init(&pipeline);
    pipeline.stop_after = options->stop_after;
    pipeline.rewrite = options->rewrite;
    pipeline.emitter = &emitter;
    pipeline.diagnostics = NULL;
@ORACLE_ASSIGNMENTS@

    result->pipeline_status = archon_pipeline_run_with_result(
        &pipeline, &pipeline_result);
    result->stage = pipeline_result.stage;
    result->stage_valid = pipeline_result.stage_valid;
    result->emitter_status = pipeline_result.emitter_status;
    result->emitter_artifact_line =
        pipeline_result.emitter_artifact_line;
    result->artifacts_retained =
        options->artifact_policy == ARCHON_EMBED_ARTIFACTS_RETAIN;
    result->output_emitted =
        result->pipeline_status == ARCHON_PIPELINE_STATUS_OK &&
        options->stop_after == ARCHON_EMBED_STAGE_EMIT;
    if (result->pipeline_status != ARCHON_PIPELINE_STATUS_OK) {
        result->status = ARCHON_EMBED_STATUS_PIPELINE_ERROR;
        AE_diagnostic(
            result, "%s",
            pipeline_result.diagnostic[0] != '\0'
                ? pipeline_result.diagnostic : "pipeline failed");
    }

    if (options->artifact_policy == ARCHON_EMBED_ARTIFACTS_DISCARD) {
        cleanup_success = AE_cleanup(
            &result->artifacts_removed,
            cleanup_diagnostic, sizeof cleanup_diagnostic);
        if (!cleanup_success) {
            if (result->status == ARCHON_EMBED_STATUS_OK) {
                result->status = ARCHON_EMBED_STATUS_CLEANUP_ERROR;
                AE_diagnostic(result, "%s", cleanup_diagnostic);
            } else {
                AE_append_diagnostic(result, cleanup_diagnostic);
            }
        }
    }
    return result->status;
}
'''


