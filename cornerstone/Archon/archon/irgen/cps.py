"""C99 continuation-passing IR generator.

The generated implementation is deliberately self contained.  ``Program.i`` is
an X-macro stream rather than generated C declarations so the same program can
be decoded by other Archon tools.  IDs in that stream are checked, not merely
ignored; this makes a truncated or accidentally reordered stream fail
deterministically.
"""

NAME = "cps"
ALIASES = ("continuation", "continuation-passing", "continuation-passing-style")


def emit_ir(context):
    """Return the two files implementing the CPS representation.

    ``context`` is accepted for the common IR-generator protocol.  CPS itself
    is architecture independent, so no context fields are consulted.
    """

    del context
    return {"IR.h": _HEADER, "IR.c": _SOURCE}


