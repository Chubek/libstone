"""Generate a standalone C99 SAT-based modulo instruction scheduler."""

from __future__ import annotations

from collections.abc import Iterable, Mapping
import re

from ..diagnostics import ArchonError


NAME = "isched"
ALIASES = ("instruction-scheduler", "modulo-scheduler", "sat-scheduler")
STAGE_ORDER = 600


def _oracle_enabled(context: object) -> bool:
    if not isinstance(context, Mapping):
        return True
    options = context.get("options", {})
    if options is None:
        options = {}
    if not isinstance(options, Mapping):
        raise ArchonError("instruction-scheduler options must be an object")
    enabled = options.get("oracle", True)
    if type(enabled) is not bool:
        raise ArchonError("instruction-scheduler option 'oracle' must be boolean")
    return enabled


def _selected_databases(context) -> list[Mapping]:
    if context is None:
        return []
    if isinstance(context, Mapping):
        if "architecture" in context and "instructions" in context:
            return [context]
        for key in ("databases", "archdbs", "targets", "architectures"):
            value = context.get(key)
            if isinstance(value, Iterable) and not isinstance(value, (str, bytes, Mapping)):
                return [item for item in value if isinstance(item, Mapping)]
        for key in ("db", "archdb", "database", "target"):
            value = context.get(key)
            if isinstance(value, Mapping):
                return [value]
    for key in ("databases", "archdbs", "targets", "architectures"):
        value = getattr(context, key, None)
        if isinstance(value, Iterable) and not isinstance(value, (str, bytes, Mapping)):
            return [item for item in value if isinstance(item, Mapping)]
    for key in ("db", "archdb", "database", "target"):
        value = getattr(context, key, None)
        if isinstance(value, Mapping):
            return [value]
    return []


def _sanitize_architecture(name: object) -> str:
    result = re.sub(r"[^A-Za-z0-9_]", "_", str(name))
    result = re.sub(r"_+", "_", result).strip("_") or "Target"
    if result[0].isdigit():
        result = "_" + result
    return result


def _c_string(value: object) -> str:
    pieces = ['"']
    for byte in str(value).encode("utf-8"):
        if byte == 0x22:
            pieces.append(r"\"")
        elif byte == 0x5C:
            pieces.append(r"\\")
        elif 0x20 <= byte <= 0x7E and byte != 0x3F:
            pieces.append(chr(byte))
        else:
            pieces.append(f"\\{byte:03o}")
    pieces.append('"')
    return "".join(pieces)


def _architecture_i(db: Mapping) -> str:
    architecture = str(db.get("architecture", "<unnamed>"))
    instructions = sorted(
        db.get("instructions", ()),
        key=lambda row: (str(row.get("id", "")), str(row.get("name", ""))),
    )
    registers = db.get("registers")
    register_count = (
        int(registers.get("count", 0)) if isinstance(registers, Mapping) else 0
    )
    lines = [
        "/* Generated by Archon ISched.",
        " * CONSERVATIVE MODEL: ArchDB schema v1 has no ports, instruction",
        " * latencies, occupancies, or register-bank constraints.  Every",
        " * instruction therefore uses one unit of one capacity-one resource",
        " * for one cycle with latency one.  Register-bank capacity is",
        " * explicitly unspecified (zero), not inferred CPU information.",
        " */",
        "#ifndef ISCHED_ARCH_BEGIN",
        "# define ISCHED_ARCH_BEGIN(architecture, instruction_count)",
        "# define ARCHON_ISCHED_UNDEF_ARCH_BEGIN",
        "#endif",
        "#ifndef ISCHED_DEFAULTS",
        "# define ISCHED_DEFAULTS(latency, occupancy, units, capacity, flags, reason)",
        "# define ARCHON_ISCHED_UNDEF_DEFAULTS",
        "#endif",
        "#ifndef ISCHED_RESOURCE",
        "# define ISCHED_RESOURCE(id, name, capacity, flags)",
        "# define ARCHON_ISCHED_UNDEF_RESOURCE",
        "#endif",
        "#ifndef ISCHED_REGISTER_BANK",
        "# define ISCHED_REGISTER_BANK(id, name, capacity, flags)",
        "# define ARCHON_ISCHED_UNDEF_REGISTER_BANK",
        "#endif",
        "#ifndef ISCHED_INSTRUCTION",
        "# define ISCHED_INSTRUCTION(name, resource, latency, occupancy, units, flags)",
        "# define ARCHON_ISCHED_UNDEF_INSTRUCTION",
        "#endif",
        "#ifndef ISCHED_ARCH_END",
        "# define ISCHED_ARCH_END()",
        "# define ARCHON_ISCHED_UNDEF_ARCH_END",
        "#endif",
        "",
        f"ISCHED_ARCH_BEGIN({_c_string(architecture)}, {len(instructions)})",
        "ISCHED_DEFAULTS(1, 1, 1, 1, ISCHED_MODEL_CONSERVATIVE,",
        '                 "ArchDB has no scheduling metadata")',
        'ISCHED_RESOURCE(0, "conservative-default", 1, ISCHED_MODEL_CONSERVATIVE)',
        (
            'ISCHED_REGISTER_BANK(0, "conservative-unspecified", '
            f"0, ISCHED_MODEL_CONSERVATIVE) /* architectural registers: "
            f"{register_count} */"
        ),
    ]
    for instruction in instructions:
        lines.append(
            f"ISCHED_INSTRUCTION({_c_string(instruction.get('name', ''))}, "
            "0, 1, 1, 1, ISCHED_MODEL_CONSERVATIVE)"
        )
    lines.extend([
        "ISCHED_ARCH_END()",
        "",
        "#ifdef ARCHON_ISCHED_UNDEF_ARCH_BEGIN",
        "# undef ISCHED_ARCH_BEGIN",
        "# undef ARCHON_ISCHED_UNDEF_ARCH_BEGIN",
        "#endif",
        "#ifdef ARCHON_ISCHED_UNDEF_DEFAULTS",
        "# undef ISCHED_DEFAULTS",
        "# undef ARCHON_ISCHED_UNDEF_DEFAULTS",
        "#endif",
        "#ifdef ARCHON_ISCHED_UNDEF_RESOURCE",
        "# undef ISCHED_RESOURCE",
        "# undef ARCHON_ISCHED_UNDEF_RESOURCE",
        "#endif",
        "#ifdef ARCHON_ISCHED_UNDEF_REGISTER_BANK",
        "# undef ISCHED_REGISTER_BANK",
        "# undef ARCHON_ISCHED_UNDEF_REGISTER_BANK",
        "#endif",
        "#ifdef ARCHON_ISCHED_UNDEF_INSTRUCTION",
        "# undef ISCHED_INSTRUCTION",
        "# undef ARCHON_ISCHED_UNDEF_INSTRUCTION",
        "#endif",
        "#ifdef ARCHON_ISCHED_UNDEF_ARCH_END",
        "# undef ISCHED_ARCH_END",
        "# undef ARCHON_ISCHED_UNDEF_ARCH_END",
        "#endif",
        "",
    ])
    return "\n".join(lines)


def emit(context=None) -> dict[str, str]:
    """Return the scheduler and one deterministic model stream per ArchDB."""
    oracle_is_enabled = _oracle_enabled(context)
    oracle_include = '#include "Oracle.h"\n' if oracle_is_enabled else ""
    oracle_support = _ORACLE_SOURCE if oracle_is_enabled else ""
    oracle_header_api = (
        "/*\n"
        " * Consume a loader-validated ISCHED sidecar without taking ownership.\n"
        " * Recognized keys are isched.operation.<id>.latency (U64),\n"
        " * isched.resource.<index>.capacity (U64), and\n"
        " * isched.operation.<id>.priority (I64).  A key is consulted only\n"
        " * when the corresponding ISched_KnownFacts bit is set.  Mark an\n"
        " * edge ISCHED_DEP_OPERATION_LATENCY when it explicitly tracks its\n"
        " * producer's operation latency.\n"
        " */\n"
        "struct ArchonOracleAnnotations;\n"
        "enum ISched_Status isched_schedule_with_annotations(\n"
        "    const ISched_Problem *problem,\n"
        "    const ISched_Options *options,\n"
        "    const ISched_KnownFacts *known,\n"
        "    const struct ArchonOracleAnnotations *annotations,\n"
        "    ISched_Result *result,\n"
        "    char *message,\n"
        "    size_t message_capacity);\n"
        if oracle_is_enabled
        else ""
    )
    oracle_prepare = (
        "    status = isched_oracle_prepare_inputs(\n"
        "        mir_path, instrmap_path, &oracle, message, message_capacity);\n"
        "    if (status != ISCHED_STATUS_SAT)\n"
        "        goto done;\n"
        if oracle_is_enabled
        else ""
    )
    oracle_apply = (
        "    status = isched_oracle_apply_facts(\n"
        "        &data, &oracle, message, message_capacity);\n"
        "    if (status != ISCHED_STATUS_SAT)\n"
        "        goto done;\n"
        if oracle_is_enabled
        else ""
    )
    oracle_priority = (
        "    status = isched_oracle_apply_priority(\n"
        "        &data, &oracle, message, message_capacity);\n"
        "    if (status != ISCHED_STATUS_SAT)\n"
        "        goto done;\n"
        if oracle_is_enabled
        else ""
    )
    oracle_outputs = (
        "    status = isched_oracle_process_outputs(\n"
        "        scheduled_path, regmap_path, status,\n"
        "        message, message_capacity);\n"
        if oracle_is_enabled
        else ""
    )
    oracle_declarations = (
        "    ISched_OracleContext oracle;\n"
        if oracle_is_enabled
        else ""
    )
    oracle_initialization = (
        "    isched_oracle_context_init(&oracle);\n"
        if oracle_is_enabled
        else ""
    )
    oracle_dispose = (
        "    isched_oracle_context_dispose(&oracle);\n"
        if oracle_is_enabled
        else ""
    )
    outputs = {
        "ISched.h": _ISCHED_H.replace("@ORACLE_API@", oracle_header_api),
        "ISched.c": (
            _ISCHED_C.replace("@ORACLE_INCLUDE@", oracle_include)
            .replace("@ORACLE_SUPPORT@", oracle_support)
            .replace("@ORACLE_DECLARATIONS@", oracle_declarations)
            .replace("@ORACLE_INITIALIZATION@", oracle_initialization)
            .replace("@ORACLE_PREPARE_INPUTS@", oracle_prepare)
            .replace("@ORACLE_APPLY@", oracle_apply)
            .replace("@ORACLE_APPLY_AFTER_MIR@", oracle_apply)
            .replace("@ORACLE_PRIORITY@", oracle_priority)
            .replace("@ORACLE_PROCESS_OUTPUTS@", oracle_outputs)
            .replace("@ORACLE_DISPOSE@", oracle_dispose)
        ),
    }
    databases = _selected_databases(context)
    for db in databases:
        stem = _sanitize_architecture(db.get("architecture", "unknown"))
        name = f"ISched_{stem}.i"
        if name in outputs:
            raise ArchonError(
                f"architecture names collide in ISched file {name!r}"
            )
        outputs[name] = _architecture_i(db)
    return outputs


