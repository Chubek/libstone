package LLSynth::Extension::QMLSpecIndex;
use strict;
use warnings;
use JSON::PP ();

# LLSynth generator extension: records the public QML frontend interface.
# It inspects the validated LLSynth spec model, not arbitrary QML source.
# Emit only deterministic, portable metadata. No shell calls or file reads.
sub render {
    my ($spec, $stem) = @_;
    $stem ||= 'qml';
    my $safe = $stem;
    $safe =~ s/[^A-Za-z0-9_.-]+/_/g;

    my @tokens = map {
        { name => $_->{name}, type => ($_->{type} || 'String'), regex => ($_->{regex} || '') }
    } @{$spec->{tokens} || []};
    my @rules = map {
        { name => $_->{name}, syntax => ($_->{facets}{syntax} || ''),
          facets => [sort keys %{$_->{facets} || {}}] }
    } @{$spec->{rules} || []};
    my @types = map {
        { name => $_->{name}, kind => ($_->{kind} || 'alias'),
          members => [ map { {name => $_->{name}, type => ($_->{type} || '')} }
                       @{$_->{members} || []} ] }
    } @{$spec->{types} || []};
    my @functions = map { { name => $_->{name} } } @{$spec->{functions} || []};
    my $manifest = {
        format => 'cephyr-qml-spec-index/1',
        language => ($spec->{language} || 'QML'),
        version => ($spec->{version} || ''),
        start => ($spec->{start} || ''),
        tokens => \@tokens,
        rules => \@rules,
        types => \@types,
        functions => \@functions,
        note => 'Grammar interface metadata only. qml/*.qpass rules are bundled separately.'
    };
    my $json = JSON::PP->new->canonical->pretty->utf8(0)->encode($manifest);
    my $markdown = "# QML frontend specification index\n\n";
    $markdown .= "Language: " . $manifest->{language} . "\n\n";
    $markdown .= "Start rule: `" . $manifest->{start} . "`\n\n";
    $markdown .= "## Grammar rules\n\n";
    for my $rule (@rules) {
        $markdown .= "- `" . $rule->{name} . "` (" . join(', ', @{$rule->{facets}}) . ")\n";
    }
    $markdown .= "\n## Declared types\n\n";
    for my $type (@types) {
        $markdown .= "- `%" . $type->{name} . "` (" . $type->{kind} . ")\n";
    }
    $markdown .= "\nGenerated by the LLSynth QMLSpecIndex extension; not a native Cephyr MIR adapter.\n";
    return { "$safe-index.json" => $json, "$safe-index.md" => $markdown };
}

1;
