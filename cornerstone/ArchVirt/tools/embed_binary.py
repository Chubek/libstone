#!/usr/bin/env python3
"""Generate a small C++ translation unit containing binary assets."""

from __future__ import annotations

import argparse
from pathlib import Path


def emit_blob(path: Path, symbol: str) -> str:
    data = path.read_bytes()
    lines = [
        f"alignas(16) extern const unsigned char {symbol}[] = {{",
    ]
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    lines.append("};")
    lines.append(f"extern const unsigned long long {symbol}_size = {len(data)}ULL;")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--symbol", required=True)
    parser.add_argument("--additional-input", type=Path, action="append", default=[])
    parser.add_argument("--additional-symbol", action="append", default=[])
    args = parser.parse_args()

    content = [
        "// Generated by domvirt/tools/embed_binary.py; do not edit.",
        "#include <cstddef>",
        "",
        "namespace domvirt::boot::embedded {",
        emit_blob(args.input, args.symbol),
    ]
    if len(args.additional_input) != len(args.additional_symbol):
        parser.error("each --additional-input requires an --additional-symbol")
    for path, symbol in zip(args.additional_input, args.additional_symbol):
        content.append(emit_blob(path, symbol))
    content.extend(["", "} // namespace domvirt::boot::embedded", ""])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(content), encoding="utf-8")


if __name__ == "__main__":
    main()
