"""Spec-derived VirtIO device catalog.

The device modules are deliberately thin public entry points.  This catalog
keeps their descriptors consistent and makes the bindlet's lookup behavior
deterministic.
"""

from __future__ import annotations

from typing import Final

from .base import (
    COMMON_FEATURES,
    VirtioAccess,
    VirtioDeviceDescriptor,
    VirtioKernelDescriptor,
    VirtioQueueDirection,
    VirtioRegistry,
    feature,
    field,
    make_device,
    make_kernel,
    queue,
)


def _spec(device: str) -> str:
    return f"third_party/virtio-spec/device-types/{device}/description.tex"


def _pair(
    device_id: int,
    name: str,
    *,
    summary: str,
    module_name: str | None = None,
    queues: tuple = (),
    features: tuple = (),
    config: tuple = (),
    aliases: tuple[str, ...] = (),
    notes: tuple[str, ...] = (),
    spec_name: str | None = None,
) -> tuple[VirtioDeviceDescriptor, VirtioKernelDescriptor]:
    spec = _spec(spec_name or name)
    descriptor = make_device(
        device_id,
        name,
        spec_ref=spec,
        summary=summary,
        queues=queues,
        features=COMMON_FEATURES + features,
        config_registers=config,
        aliases=aliases,
        notes=notes,
    )
    kernel = make_kernel(
        device_id,
        name,
        module=f"domainlet.vmm.virtio.{module_name or name}",
        spec_ref=spec,
        description=summary,
        notes=notes,
    )
    return descriptor, kernel


