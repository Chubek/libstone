def get_pair(name: str) -> tuple[VirtioDeviceDescriptor, VirtioKernelDescriptor]:
    normalized = name.strip().lower()
    if normalized.startswith("domainlet.vmm.virtio."):
        normalized = normalized.removeprefix("domainlet.vmm.virtio.")
    if normalized.endswith(".py"):
        normalized = normalized[:-3]
    for key, pair in DEVICE_PAIRS.items():
        if normalized == key or normalized in pair[0].identifiers:
            return pair
    raise KeyError(f"unknown VirtIO device module: {name}")


