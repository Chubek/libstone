std::string emit_wit_c(const WitDocument& document) {
    return emit_wit_c(document, {});
}

std::string emit_wit_c(const WitDocument& document, std::span<const WitDocument> dependencies) {
    validate_wit(document);
    return WitBindings(document, dependencies).emit();
}

std::string wit_to_c(std::string_view source) {
    const auto document = parse_wit(source);
    return WitBindings(document).emit(); // parse_wit already validated the document.
}

std::vector<canonical::Function> canonical::resolve(const WitDocument& document,
                                                     std::span<const WitDocument> dependencies) {
    validate_wit(document);
    return WitBindings(document, dependencies).canonical_functions();
}

