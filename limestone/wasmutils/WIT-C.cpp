std::string_view scalar_type(WitScalar scalar, WitLocation location) {
    switch (scalar) {
    case WitScalar::Bool: return "int";
    case WitScalar::U8: return "unsigned char";
    case WitScalar::S8: return "signed char";
    case WitScalar::U16: return "wit_host_u16";
    case WitScalar::S16: return "wit_host_s16";
    case WitScalar::U32: return "wit_host_u32";
    case WitScalar::S32: return "wit_host_s32";
    case WitScalar::U64: return "wit_host_u64";
    case WitScalar::S64: return "wit_host_s64";
    case WitScalar::F32: return "float";
    case WitScalar::F64: return "double";
    case WitScalar::Char: return "wit_host_u32";
    }
    throw WitError(location, "invalid WIT scalar type in AST");
}

std::string label(const WitName& name) {
    std::string result;
    for (char c : name.text) {
        if (c == '-')
            c = '_';
        else if (c >= 'A' && c <= 'Z')
            c = static_cast<char>(c - 'A' + 'a');
        result += c;
    }
    return result;
}

std::string key(const WitName& name) {
    auto result = label(name);
    result.erase(std::remove(result.begin(), result.end(), '_'), result.end());
    return result;
}

// The separator cannot appear inside a folded WIT label. Keep the legacy
// freestanding syntax unchanged and reserve other separators for new names.
constexpr auto sep = "_W_";
constexpr char hex[] = "0123456789ABCDEF";

std::string package_prefix(const std::optional<WitPackage>& package) {
    std::string prefix = "wit_";
    if (package) {
        prefix += label(package->name_space) + sep + label(package->name) + sep;
        if (package->version) {
            prefix += 'v';
            const auto& version = package->version->text;
            const auto suffix = version.find_first_of("-+");
            for (const char c : std::string_view(version).substr(0, suffix))
                prefix += c == '.' ? 'v' : c;
            if (suffix != std::string::npos) {
                prefix += "_V_";
                for (const char ch : std::string_view(version).substr(suffix)) {
                    const auto c = static_cast<unsigned char>(ch);
                    prefix += hex[c >> 4];
                    prefix += hex[c & 0xf];
                }
            }
            prefix += sep;
        }
    }
    return prefix;
}

std::string stable_hash(std::string_view text) {
    std::uint64_t hash = 14695981039346656037ULL;
    for (const char c : text) {
        hash ^= static_cast<unsigned char>(c);
        hash *= 1099511628211ULL;
    }
    std::string result;
    for (int shift = 60; shift >= 0; shift -= 4)
        result += hex[(hash >> shift) & 0xf];
    return result;
}

