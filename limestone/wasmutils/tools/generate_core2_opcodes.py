#!/usr/bin/env python3
"""Refresh the Core 2.0 opcode table from a local copy of the pinned W3C spec."""

import argparse
from collections import Counter
import hashlib
from html.parser import HTMLParser
from pathlib import Path
import re


SPEC = "https://www.w3.org/TR/2025/CRD-wasm-core-2-20250616/"
SHA256 = "e15693addb533d01add85bb4fb80a80796eb6107bb1e5530032f28209031869e"
TABLE = Path(__file__).resolve().parents[1] / "WASM-Core-Opcodes.inc"


class MathText(HTMLParser):
    def __init__(self, font):
        super().__init__()
        self.font = font
        self.spans = []
        self.text = []

    def handle_starttag(self, tag, attrs):
        if tag == "span":
            self.spans.append(self.font in dict(attrs).get("class", "").split())

    def handle_endtag(self, tag):
        if tag == "span" and self.spans:
            self.spans.pop()

    def handle_data(self, data):
        if any(self.spans):
            self.text.append(data)


def math_text(cell, font):
    parser = MathText(font)
    parser.feed(cell)
    parser.close()
    return "".join(parser.text)


def immediate(byte, ext):
    if byte == 0xFC:
        if ext < 8:
            return "none"
        if ext in (8, 10, 11):
            return {8: "index_zero", 10: "zero_zero", 11: "zero"}[ext]
        return "index_pair" if ext in (12, 14) else "index"
    if byte == 0xFD:
        if ext < 0x0C or ext in (0x5C, 0x5D):
            return "memory"
        if ext in (0x0C, 0x0D):
            return "vector_bytes"
        if 0x15 <= ext <= 0x22:
            return "lane"
        if 0x54 <= ext <= 0x5B:
            return "memory_lane"
        return "none"
    if 0x28 <= byte <= 0x3E:
        return "memory"
    if byte in (0x0C, 0x0D, 0x10, 0xD2) or 0x20 <= byte <= 0x26:
        return "index"
    if 0x02 <= byte <= 0x04:
        return "block"
    if 0x41 <= byte <= 0x44:
        return ("i32", "i64", "f32", "f64")[byte - 0x41]
    return {0x0E: "branch_table", 0x11: "index_pair", 0x1C: "types",
            0x3F: "zero", 0x40: "zero", 0xD0: "ref_type"}.get(byte, "none")


def generate(html):
    heading = html.index('id="a8-index-of-instructions"')
    start = html.index("<tbody>", heading)
    end = html.index("</table>", start)
    ops = {}
    for row in html[start:end].split("<tr")[1:]:
        cells = row.split("<td")[1:3]
        if len(cells) != 2:
            raise ValueError("unexpected row layout in instruction index")
        name = math_text(cells[0], "mathsf")
        if not name:  # Reserved rows have no mnemonic.
            continue
        name = re.sub(r"^((?:[if](?:8|16|32|64)x(?:2|4|8|16)|[if](?:32|64)|v128))(?=[a-z])",
                      r"\1.", name)
        name = re.sub(r"(\.const)([if](?:32|64)|v128)$", r"\1", name)
        if not re.fullmatch(r"[a-z][a-z0-9_.]*", name):
            raise ValueError(f"invalid mnemonic: {name}")
        opcode = math_text(cells[1], "mathtt")
        if not re.fullmatch(r"(?:0x[0-9A-F]{2}){1,3}", opcode):
            raise ValueError(f"invalid opcode: {opcode}")
        first, *leb = bytes.fromhex(opcode.replace("0x", " "))
        if (first in (0xFC, 0xFD)) != bool(leb):
            raise ValueError(f"unexpected opcode prefix: {opcode}")
        if leb and (leb[-1] >= 0x80 or (len(leb) > 1 and leb[-1] == 0)
                    or any(b < 0x80 for b in leb[:-1])):
            raise ValueError(f"noncanonical extension in index: {opcode}")
        ext = sum((b & 0x7F) << (7 * i) for i, b in enumerate(leb))
        if (first, ext) in ops:
            raise ValueError(f"duplicate opcode: {opcode}")
        ops[first, ext] = name

    groups = Counter(b if b in (0xFC, 0xFD) else 0 for b, _ in ops)
    if groups != {0: 183, 0xFC: 18, 0xFD: 236}:
        raise ValueError(f"unexpected Core 2.0 opcode counts: {groups}")
    duplicates = {name: n for name, n in Counter(ops.values()).items() if n > 1}
    if duplicates != {"select": 2}:
        raise ValueError(f"unexpected duplicate mnemonics: {duplicates}")
    return (
        "// Generated by tools/generate_core_opcodes.py from W3C Core 2.0, Appendix A.8.\n"
        f"// {SPEC}#index-instr\n"
        "// Immediate formats follow sections 5.2 and 5.4.\n"
        + "".join(f'    {{{{0x{b:02x}, 0x{ext:02x}}}, "{name}", Format::{immediate(b, ext)}}},\n'
                  for (b, ext), name in sorted(ops.items()))
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__, epilog=f"Source: {SPEC}")
    parser.add_argument("spec_html", type=Path)
    parser.add_argument("--check", action="store_true", help="verify the checked-in table")
    args = parser.parse_args()
    html = args.spec_html.read_bytes()
    if hashlib.sha256(html).hexdigest() != SHA256:
        parser.error("HTML does not match the pinned Core 2.0 document")
    output = generate(html.decode("utf-8")).encode("ascii")
    if args.check:
        if TABLE.read_bytes() != output:
            parser.error(f"{TABLE.name} is not up to date")
    else:
        TABLE.write_bytes(output)


if __name__ == "__main__":
    main()
