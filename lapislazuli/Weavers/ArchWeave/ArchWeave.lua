-- Declarative fixed-width native instruction codecs. Lua 5.4; emitted C99.
local here = debug.getinfo(1, "S").source:sub(2):match("^(.*)/[^/]*$") or "."
local c = dofile(here .. "/../common.lua")
local M, methods = { version = "1" }, {}
methods.__index = methods

local function validate(spec)
  c.keys(spec, { name=true, arch=true, machine=true, word_bits=true, address_bits=true,
    endian=true, source=true, instructions=true }, "architecture")
  c.name(spec.name); c.text(spec.arch, "BFD architecture"); c.text(spec.source, "reference")
  c.integer(spec.machine, 0, 0xffffffff, "BFD machine")
  c.integer(spec.word_bits, 8, 64, "word bits"); c.integer(spec.address_bits, 8, 64, "address bits")
  assert(spec.endian == "big" or spec.endian == "little", "invalid byte order")
  c.list(spec.instructions, "instructions")
  assert(#spec.instructions > 0, "architecture needs instructions")
  local names = {}
  for index, word in ipairs(spec.instructions) do
    c.keys(word, { name=true, match=true, mask=true, operands=true }, "instruction")
    assert(type(word.name) == "string" and word.name:match("^[a-z][a-z0-9_.]*$"), "invalid mnemonic")
    assert(not names[word.name], "duplicate instruction " .. word.name); names[word.name] = true
    c.integer(word.match, 0, 0xffffffff, "instruction match")
    c.integer(word.mask, 1, 0xffffffff, "instruction mask")
    assert((word.match & word.mask) == word.match, "match outside mask")
    c.list(word.operands, "operands"); assert(#word.operands <= 6, "at most six operands")
    local used, fields = word.mask, {}
    for _, field in ipairs(word.operands) do
      c.keys(field, { name=true, shift=true, bits=true, signed=true, scale=true }, "operand")
      assert(type(field.name) == "string" and field.name:match("^[a-z][a-z0-9_]*$"), "invalid operand name")
      assert(not fields[field.name], "duplicate operand " .. field.name); fields[field.name] = true
      c.integer(field.shift, 0, 31, "operand shift"); c.integer(field.bits, 1, 32, "operand bits")
      assert(field.shift + field.bits <= 32, "operand exceeds instruction")
      assert(field.signed == nil or type(field.signed) == "boolean", "signed must be boolean")
      local scale = field.scale or 1
      assert(scale == 1 or scale == 2 or scale == 4 or scale == 8, "invalid operand scale")
      local mask = ((1 << field.bits) - 1) << field.shift
      assert((used & mask) == 0, "overlapping operand bits"); used = used | mask
    end
    assert(used == 0xffffffff, "every instruction bit must be fixed or an operand")
    for previous = 1, index - 1 do
      local other = spec.instructions[previous]
      assert(((word.match ~ other.match) & word.mask & other.mask) ~= 0,
        "ambiguous instruction encodings: " .. word.name .. " and " .. other.name)
    end
  end
end

function M.arch(spec)
  validate(spec)
  local result = c.copy(spec)
  table.sort(result.instructions, function(a, b) return a.name < b.name end)
  return setmetatable(result, methods)
end

function M.load(path) return c.load(path, "ArchWeave", methods) end

function methods:emit_header()
  validate(self)
  return c.render([[/* Generated by ArchWeave 1; edit the .archw description. */
#ifndef @NAME@_ARCHWEAVE_H
#define @NAME@_ARCHWEAVE_H
#include <stddef.h>
#include <stdint.h>
#ifdef __cplusplus
extern "C" {
#endif
typedef struct {
  const char *name;
  unsigned shift, bits, is_signed, scale;
} @NAME@_operand;
typedef struct {
  const char *name;
  uint32_t match, mask;
  size_t operand_count;
  @NAME@_operand operands[6];
} @NAME@_instruction;
typedef struct {
  const char *arch, *source;
  uint32_t machine;
  unsigned word_bits, address_bits, little_endian;
} @NAME@_architecture;
typedef struct {
  const @NAME@_instruction *instruction;
  size_t count;
  int64_t operands[6];
} @NAME@_decoded;
/* 0 success; -1 unknown encoding/mnemonic; -2 short buffer; -3 invalid argument.
 * Outputs remain unchanged on error. Byte order must be 0 (big) or 1 (little).
 * Displacements are signed byte offsets (scaled fields), not resolved addresses.
 * Mnemonics are exact, case-sensitive encoding names, not an assembly parser. */
const @NAME@_architecture *@NAME@_info(void);
const @NAME@_instruction *@NAME@_instructions(size_t *count);
const @NAME@_instruction *@NAME@_lookup(const char *name);
int @NAME@_encode_word(const char *name, const int64_t *values, size_t count, uint32_t *out);
int @NAME@_decode_word(uint32_t word, @NAME@_decoded *out);
int @NAME@_encode(const char *name, const int64_t *values, size_t count,
                  void *data, size_t size, int little_endian);
int @NAME@_decode(const void *data, size_t size, int little_endian, @NAME@_decoded *out);
#ifdef __cplusplus
}
#endif
#endif
]], { NAME=self.name })
end

function methods:emit()
  validate(self)
  local words = {}
  for _, word in ipairs(self.instructions) do
    local fields = {}
    for _, field in ipairs(word.operands) do
      fields[#fields+1] = string.format("{ %s, %d, %d, %d, %d }", c.quote(field.name),
        field.shift, field.bits, field.signed and 1 or 0, field.scale or 1)
    end
    if #fields == 0 then fields[1] = "{ 0, 0, 0, 0, 0 }" end
    words[#words+1] = string.format("  { %s, UINT32_C(0x%08x), UINT32_C(0x%08x), %d, { %s } }",
      c.quote(word.name), word.match, word.mask, #word.operands, table.concat(fields, ", "))
  end
  return c.render(c.read(here .. "/runtime.c.in"), {
    NAME=self.name, WORDS=table.concat(words, ",\n"), ARCH=c.quote(self.arch),
    SOURCE=c.quote(self.source), MACHINE=tostring(self.machine), WORD_BITS=tostring(self.word_bits),
    ADDRESS_BITS=tostring(self.address_bits), LITTLE=self.endian == "little" and "1" or "0",
  })
end

return M
