"""Generate the reviewed C++17 OptParser / Directives profile, not a LibDSL bundle."""
import argparse
import hashlib
from pathlib import Path


def reviewed(path, digest):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != digest:
        raise SystemExit(f"{path}: changed; review source ranges and notices first")
    return data.decode("utf-8")


def generate(root):
    source = reviewed(root / "firestone/libdsl/LibDSL.hpp",
                      "8cafa81d9a2177afe27d95769e234dc668fe2d7e83c1be3544b59f9abea910e2")
    license_text = reviewed(root / "LICENSE",
                            "b6b3e1c6797e1952a82ab917ed111bcb5f1e51e36bd1eeb1ca8f35780dcaf972")
    lines = source.split("\n")

    def take(first, last):
        return "\n".join(lines[first - 1:last]) + "\n"

    # Native command schemas, argument parsing, validation, directive tokenization
    # and dispatch. Exclude styled terminal help, schema readers and scripts.
    profile = (take(17634, 17796) + take(17813, 18012) + """
public:
  std::string help (const std::vector<std::string> &path = {}) const
  {
    return resolve (path).back ()->description;
  }
""" + take(18274, 18290) + take(18328, 18782) + "};\n}\nnamespace repl {\n"
               + take(19649, 19653) + take(22732, 22811) + take(22823, 22845)
               + take(22873, 22916) + "};\n}\n")
    for old, new in [
        ("options.contains (std::string (name))", "options.count (std::string (name)) != 0"),
        ("canonical.contains (name)", "canonical.count (name)"),
        ('arg.starts_with ("--")', 'arg.substr (0, 2) == "--"'),
        ('name.starts_with ("no-")', 'name.substr (0, 3) == "no-"'),
        ("rest.starts_with ('=')", "(!rest.empty () && rest.front () == '=')"),
        # Keep diagnostics printable without pulling in Unicode terminal tables.
        ("return terminal::sanitize_text (text);", """std::string result;
    for (unsigned char c : text)
      result += (c >= 32 && c <= 126) ? static_cast<char> (c) : '?';
    return result;"""),
    ]:
        assert old in profile, old
        profile = profile.replace(old, new)
    includes = ("algorithm charconv cmath cstdint cstdlib functional limits map "
                "optional stdexcept string string_view unordered_map unordered_set "
                "utility variant vector")
    return ("// Generated by amalgam8/extract_frontend.py from firestone/libdsl/LibDSL.hpp.\n"
            "/*\n" + license_text + "*/\n#pragma once\n"
            + "".join(f"#include <{h}>\n" for h in includes.split())
            + "\nnamespace smtlib2::detail::firestone_frontend {\n" + profile + "}\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_bytes(generate(args.root).encode("utf-8"))
