-- Target-specific, allocation-free ELF readers. Not a libbfd ABI replacement.
local here = debug.getinfo(1, "S").source:sub(2):match("^(.*)/[^/]*$") or "."
local c = dofile(here .. "/../common.lua")
local M, methods = { version="1" }, {}
methods.__index = methods

local function validate(spec)
  c.keys(spec, { name=true, target=true, arch=true, class=true, endian=true, machine=true, source=true }, "ELF target")
  c.name(spec.name); c.text(spec.target, "target name"); c.text(spec.arch, "architecture")
  c.text(spec.source, "reference")
  assert(spec.class == 32 or spec.class == 64, "ELF class must be 32 or 64")
  assert(spec.endian == "big" or spec.endian == "little", "invalid ELF byte order")
  c.integer(spec.machine, 1, 65535, "ELF machine")
end

function M.elf(spec)
  validate(spec)
  return setmetatable(c.copy(spec), methods)
end
function M.load(path) return c.load(path, "BFDWeave", methods) end

