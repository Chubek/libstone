function methods:emit()
  validate(self)
  return c.render(c.read(here .. "/runtime.c.in"), {
    NAME=self.name, TARGET=c.quote(self.target), ARCH=c.quote(self.arch), SOURCE=c.quote(self.source),
    CLASS=tostring(self.class), CLASS_ID=self.class == 64 and "2" or "1",
    LITTLE=self.endian == "little" and "1" or "0", ENDIAN_ID=self.endian == "little" and "1" or "2",
    MACHINE=tostring(self.machine), HEADER_SIZE=self.class == 64 and "64" or "52",
    SECTION_SIZE=self.class == 64 and "64" or "40", SEGMENT_SIZE=self.class == 64 and "56" or "32",
  })
end
return M
