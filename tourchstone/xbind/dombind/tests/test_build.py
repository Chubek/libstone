"""Exercise installed CMake packages and standalone generation entry points."""
from pathlib import Path
import shutil
import sys
import tempfile
import unittest

from test_bindings import ROOT, LANGUAGES, flags, run, tool

TITLES = dict(d='D', go='Go', java='Java', lua='Lua', node='Node',
              ocaml='OCaml', ruby='Ruby', rust='Rust')


class Build(unittest.TestCase):
    def test_generator_entry_points(self):
        with tempfile.TemporaryDirectory(prefix='dombind-generate-') as tmp:
            output = Path(tmp)/'include/capi.h'
            for lang in LANGUAGES:
                with self.subTest(language=lang):
                    run([sys.executable, ROOT/f'dom{lang}bind/generate.py', output])
                    self.assertIn('Generated by Q', output.read_text())
            run([sys.executable, ROOT/'generate.py', 'go', output,
                 '--module', 'gobuf', '--prefix', 'test_buffer'])
            self.assertIn('test_buffer_copy', output.read_text())

    def test_installed_consumers(self):
        cmake = tool('cmake')
        selected = []
        for lang in LANGUAGES:
            try:
                flags(lang)
            except unittest.SkipTest:
                continue
            selected.append(lang)
        with tempfile.TemporaryDirectory(prefix='dombind-cmake-') as tmp:
            path = Path(tmp)
            build, install, consumer = path/'build', path/'install', path/'consumer'
            run([cmake, '-S', ROOT, '-B', build, '-DCMAKE_INSTALL_PREFIX='+str(install),
                 '-DPython3_EXECUTABLE='+sys.executable,
                 *[f'-DDOMBIND_{lang.upper()}=ON' for lang in selected]])
            run([cmake, '--build', build, '--parallel', '2'])
            run([cmake, '--install', build])
            consumer.mkdir()
            config = ['cmake_minimum_required(VERSION 3.20)', 'project(Consumer LANGUAGES C CXX)']
            executable_languages = []
            for lang in selected:
                package = 'Dom'+TITLES[lang]+'Bind'
                config.append(f'find_package({package} CONFIG REQUIRED)')
                if lang == 'node':
                    shutil.copyfile(ROOT/'domnodebind/examples/addon.cpp', consumer/'node.cpp')
                    config.append('domnodebind_add_module(node node.cpp)')
                elif lang == 'ocaml':
                    (consumer/'ocaml.cpp').write_text('#include <domocamlbind/domocamlbind.hpp>\n')
                    config.append('add_library(ocaml OBJECT ocaml.cpp)')
                    config.append(f'target_link_libraries(ocaml PRIVATE {package}::{package})')
                else:
                    example = ROOT/f'dom{lang}bind/examples/embed.cpp'
                    if example.exists():
                        shutil.copyfile(example, consumer/f'{lang}.cpp')
                    else:
                        (consumer/f'{lang}.cpp').write_text(
                            f'#include <dom{lang}bind/dom{lang}bind.hpp>\n'
                            f'int main() {{ dom{lang}bind::buffer b("ok", 2); return b.size() == 2 ? 0 : 1; }}\n')
                    config.append(f'add_executable({lang} {lang}.cpp)')
                    config.append(f'target_link_libraries({lang} PRIVATE {package}::{package})')
                    executable_languages.append(lang)
            (consumer/'CMakeLists.txt').write_text('\n'.join(config)+'\n')
            # The consumer is a separate configure with only the installed prefix.
            run([cmake, '-S', consumer, '-B', path/'consumer-build', '-DCMAKE_PREFIX_PATH='+str(install)])
            run([cmake, '--build', path/'consumer-build', '--parallel', '2'])
            for lang in executable_languages:
                with self.subTest(language=lang):
                    run([path/'consumer-build'/lang])
            if 'node' in selected:
                run([tool('node'), '-e',
                     'if (require(process.argv[1]).answer !== 42) process.exit(1)',
                     path/'consumer-build/node.node'])


if __name__ == '__main__':
    unittest.main()
